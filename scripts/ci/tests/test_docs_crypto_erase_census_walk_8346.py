def erasable_bytes(clean, scope_clean):
    """Return the sorted `0x..` strings for CRYPTO_ERASABLE_ENVELOPE_VERSIONS (RECORD, SCOPE).

    The census `let bytes` expression is pinned with the rest of the census region. Here the whole
    array is parsed: a `const` (anchored on `const`, with an optional `pub`), declared exactly once
    of any kind, typed `[u8; N]`, every element a constant name declared once as
    `const NAME: u8 = 0x..;` (a numeric literal such as `0x07`, an expression or an unknown name
    raises AssertionError instead of being dropped), N equal to the element count. The result is a
    sorted set: the Rust census result does not depend on the order or on a repeated element.
    """
    declared_name_once(mask_literals(clean), "CRYPTO_ERASABLE_ENVELOPE_VERSIONS",
                       "const CRYPTO_ERASABLE_ENVELOPE_VERSIONS")
    array = (r"\b(?:pub(?:\([^)]*\))?\s+)?const\s+CRYPTO_ERASABLE_ENVELOPE_VERSIONS\s*:"
             r"\s*\[u8;\s*(\d+)\s*\]\s*=\s*\[(.*?)\];")
    if not masked_matches(clean, array, re.S):
        raise AssertionError("%s no longer declares CRYPTO_ERASABLE_ENVELOPE_VERSIONS as a const [u8; N]"
                             % RUST_SRC)
    match = one_match(clean, array, "const CRYPTO_ERASABLE_ENVELOPE_VERSIONS: [u8; N]", re.S)
    length, body = clean[match.start(1):match.end(1)], clean[match.start(2):match.end(2)]
    elements = [compact(part) for part in body.split(",")]
    if elements and elements[-1] == "":
        elements.pop()
    if len(elements) != int(length) or "" in elements:
        raise AssertionError("%s: CRYPTO_ERASABLE_ENVELOPE_VERSIONS declares [u8; %s] but %d elements "
                             "were parsed: %r" % (RUST_SRC, length, len(elements), elements))
    masked = mask_literals(clean) + "\n" + mask_literals(scope_clean)
    values, seen = {}, {}
    for src in (clean, scope_clean):
        for found in masked_matches(src, r"const ([A-Z_]+_ENVELOPE_VERSION)\s*:\s*u8\s*=\s*0x([0-9a-fA-F]+);"):
            name = src[found.start(1):found.end(1)]
            seen[name] = seen.get(name, 0) + 1
            values[name] = int(src[found.start(2):found.end(2)], 16)
    for name, count in seen.items():
        if count != 1:
            raise AssertionError("%s (or %s): `const %s: u8` is declared %d times outside string literals, the "
                                 "value reader needs exactly one" % (RUST_SRC, SCOPE_SRC, name, count))
    for element in elements:
        if element not in values:
            raise AssertionError("%s: CRYPTO_ERASABLE_ENVELOPE_VERSIONS element %r is not a known "
                                 "`*_ENVELOPE_VERSION` constant of %s or %s (round 13: both files named, the "
                                 "constant may have been removed or made private in %s)"
                                 % (RUST_SRC, element, RUST_SRC, SCOPE_SRC, SCOPE_SRC))
        declared_name_once(masked, element, "const " + element, "%s and %s" % (RUST_SRC, SCOPE_SRC))
    return sorted({"0x%02x" % values[element] for element in elements})


def literals_only(clean, name, single=False):
    """Raise unless the body of `const <name>` holds string literals only (and exactly one when `single`).

    The mirror parses the string literals of the parsed constants. A `concat!`, a method call, a `b"..."` or an
    identifier in the body changes the value Rust computes without changing the literals the parser sees, so
    after the literals are masked only `[`, `]`, `,` and whitespace may remain.
    """
    body = const_body(clean, name)
    residue = re.sub(r"[\s\0\[\],]", "", mask_literals(body))
    if residue or (single and len(strings(body)) != 1):
        raise AssertionError("%s: %s must hold string literals only (found %r besides the literals): a macro, a "
                             "call or an identifier in the body changes the value the census reads"
                             % (RUST_SRC, name, residue or body.strip()[:40]))


MACRO_NAME = re.compile(r"(?<![\w'#])macro_rules\s*!\s*(?:r#)?([^\s{(\[]+)")


def plain_macros(masked, where):
    """Return the names of the `macro_rules!` of the masked source; a computed name (`$name`) raises."""
    names = []
    for match in MACRO_NAME.finditer(masked):
        if not re.fullmatch(r"[A-Za-z_]\w*", match.group(1)):
            raise AssertionError("%s defines `macro_rules! %s`, a name the mirror cannot read" % (where, match.group(1)))
        names.append(match.group(1))
    return names


@functools.lru_cache(maxsize=32)
def reject_crate_level(lib_clean, macros):
    """Scan the stripped src/lib.rs up to `pub mod encryption;`; return the macros defined there.

    A textual `macro_rules!` defined before the module declaration is in scope inside mod.rs, so one named like
    a macro the census region invokes (`macros`, derived from the region) would replace it without touching a
    byte of the region. `#[macro_use]`, `no_implicit_prelude`, `include!`, `extern crate` and any attribute or
    visibility change on the declaration are rejected as well.
    """
    masked = mask_literals(lib_clean)
    if re.search(r"\bextern\s+crate\b", masked):
        raise AssertionError("%s contains `extern crate`: it adds a crate to the extern prelude, so `std` could "
                             "name another crate in mod.rs" % LIB_SRC)
    found = list(re.finditer(r"(?<![\w'#])mod\s+(?:r#)?encryption\b", masked))
    if len(found) != 1:
        raise AssertionError("%s must declare `mod encryption` exactly once, found %d" % (LIB_SRC, len(found)))
    depth = masked.count("{", 0, found[0].start()) - masked.count("}", 0, found[0].start())
    if depth != 0:
        raise AssertionError("%s declares `mod encryption` at brace depth %d: it is `crate::<outer>::encryption`, "
                             "not the module the census region lives in" % (LIB_SRC, depth))
    rebound = use_bindings(masked, "encryption", LIB_SRC, reexport_ok=False)
    if rebound:
        raise AssertionError("%s has `%s` that binds the name `encryption`: it can rebind the module the census "
                             "region lives in" % (LIB_SRC, rebound[0]))
    end = masked.index(";", found[0].start()) + 1
    begin = max(masked.rfind(c, 0, found[0].start()) for c in ";{}") + 1
    header = compact(lib_clean[begin:end])
    if header != LIB_MOD:
        raise AssertionError("%s: the declaration of the encryption module is `%s`, expected `%s` (an attribute "
                             "such as `path` or `cfg`, or another visibility, loads other code or compiles it out)"
                             % (LIB_SRC, header, LIB_MOD))
    prefix = masked[:end]
    if re.search(r"[^\x00-\x7f]", prefix):
        raise AssertionError("%s has a non-ASCII character before `mod encryption;` outside a literal" % LIB_SRC)
    reject_attributes(prefix, LIB_SRC, CRATE_DENIED_ATTRIBUTE_WORDS)
    if re.search(r"\binclude\s*!", prefix):
        raise AssertionError("%s has `include!` before `mod encryption;`: it pulls in code the mirror never reads"
                             % LIB_SRC)
    defined = plain_macros(prefix, LIB_SRC)
    for name in defined:
        if name in macros:
            raise AssertionError("%s defines the `macro_rules!` macro `%s` before `mod encryption;`, and the "
                                 "census region invokes `%s!`: the local macro would replace it inside mod.rs"
                                 % (LIB_SRC, name, name))
    # r13: the whole file is read, so a macro defined AFTER the declaration is a macro too (it can emit a module
    # declaration): only the pinned macro of the live file is allowed anywhere.
    for name in plain_macros(masked, LIB_SRC):
        if name not in LIB_KNOWN_MACROS:
            raise AssertionError("%s defines the `macro_rules!` macro `%s`, which the pin %r does not list: a macro "
                                 "of src/lib.rs can emit a module declaration or an item the mirror never reads"
                                 % (LIB_SRC, name, LIB_KNOWN_MACROS))
    return tuple(defined)


# ---- src/lib.rs read whole (#8346 round 13) ----
# Characters rustc skips or reads as whitespace that Python's `\s` does not match (Pattern_White_Space, the zero-width
# and bidi format characters, the no-break and ideographic spaces): U+200B-U+200F, U+2028, U+2029, U+202A-U+202E,
# U+2060-U+2064, U+FEFF, U+00A0, U+1680, U+2000-U+200A, U+205F, U+3000 (and U+0085).
UNICODE_SPACE = frozenset(
    list(range(0x200B, 0x2010)) + [0x2028, 0x2029] + list(range(0x202A, 0x202F)) + list(range(0x2060, 0x2065))
    + [0xFEFF, 0x00A0, 0x1680] + list(range(0x2000, 0x200B)) + [0x205F, 0x3000, 0x0085])
# The only module declarations src/lib.rs may carry for the names the mirror resolves, as compact headers.
LIB_PINNED_MODS = {"encryption": "pubmodencryption;", "test_support": "#[cfg(test)]modtest_support;"}
# The inner attributes src/lib.rs carries today, compact: any other `#![...]` changes how the whole crate is read.
LIB_INNER_ATTRIBUTES = ('recursion_limit="512"', "allow(clippy::pedantic,clippy::all)")


def reject_unicode_space(masked, rel):
    """Raise a named error on the first non-ASCII character outside a comment or literal of `masked`.

    rustc reads U+200E, U+200F and the other characters of `UNICODE_SPACE` as whitespace, Python's `\\s` does
    not, so `mod<U+200E>test_support;` is a declaration for rustc and invisible to every regex of this guard
    (#8346 round 12, security LOW-2). Any other non-ASCII character is a look-alike identifier risk.
    """
    found = re.search(r"[^\x00-\x7f]", masked)
    if found is not None:
        char = found.group(0)
        what = ("a Unicode whitespace, format or bidi character" if ord(char) in UNICODE_SPACE
                else "a non-ASCII character")
        raise AssertionError("%s has %s U+%04X (%s) outside a comment or literal at offset %d: rustc may read it as "
                             "whitespace or as part of an identifier, the mirror's regexes do not, so a declaration "
                             "or attribute could hide behind it"
                             % (rel, what, ord(char), unicodedata.name(char, "unnamed"), found.start()))


def lib_module_items(lib_clean, masked):
    """Return [(name, terminator, compact header)] for every top-level `mod` item of src/lib.rs.

    The whole file is walked as a sequence of top-level items (attributes read with the bracket-balanced parser the
    use-target reader uses, never a look-back for `;`, `{` or `}`); a top-level macro invocation or a shape the
    walker does not know raises, so a declaration cannot hide in a place nobody read.
    """
    top = top_level(masked)
    pos, mods = 0, []
    while True:
        while pos < len(top) and top[pos].isspace():
            pos += 1
        if pos >= len(top):
            break
        pos, spans = read_attributes(top, pos, LIB_SRC)
        if pos >= len(top):
            break
        outer = [span for span in spans if not span[0]]
        begin = outer[0][3] if outer else pos
        header = ITEM_HEADER.match(top, pos)
        if header is None:
            macro = ITEM_MACRO.match(top, pos)
            if macro is not None:
                raise AssertionError("%s invokes the macro `%s!` at the top level: a macro can emit a module "
                                     "declaration the mirror never reads" % (LIB_SRC, re.sub(r"\s+", "", macro.group(1))))
            raise AssertionError("%s has a top-level item the whole-file reader does not name: `%s`"
                                 % (LIB_SRC, re.sub(r"\s+", " ", top[pos:pos + 48]).strip()))
        kind = header.group(2)
        stop = item_end(top, header.end(), "fn" if kind in ("extern", "macro_rules") else kind, LIB_SRC)
        if kind == "mod":
            name = ITEM_NAME.match(top, header.end())
            if name is None:
                raise AssertionError("%s has a top-level `mod` item without a name the mirror can read" % LIB_SRC)
            after = re.compile(r"\s*([;{])").match(top, name.end())
            if after is None:
                raise AssertionError("%s has `mod %s` that is neither `;` nor `{` terminated" % (LIB_SRC, name.group(1)))
            mods.append((name.group(1), after.group(1), compact(lib_clean[begin:after.end()]), begin, pos))
        pos = stop
    return mods


@functools.lru_cache(maxsize=32)
def read_lib_whole(lib_clean):
    """Read src/lib.rs whole as masked text; raise on a hidden, nested, repeated or re-attributed declaration.

    #8346 round 13 (code LOW-1 = security LOW-2): rounds 11 and 12 read a prefix of the file and found the
    `test_support` declaration with a look-back regex; both failed review on the same class (an input read partially
    or matched as text where rustc resolves names). The whole file is now the input, like every other file: no
    Unicode whitespace, format or bidi character outside a comment or literal, no `cfg_attr` or `path` attribute and
    no `include!` anywhere, only the live inner attributes, and the two declarations the mirror resolves pinned exactly.
    Returns the tuple of (name, terminator, compact header) of the top-level `mod` items.
    """
    masked = mask_literals(lib_clean)
    reject_unicode_space(masked, LIB_SRC)
    items = lib_module_items(lib_clean, masked)
    for name in sorted(LIB_PINNED_MODS):
        top_level_found = [item[2] for item in items if item[0] == name]
        anywhere = len(re.findall(r"(?<![\w'#])mod\s+(?:r#)?%s\b" % re.escape(name), masked))
        if name != "encryption" and (len(top_level_found) != 1 or anywhere != 1):
            raise AssertionError("%s must declare `mod %s;` exactly once at the top level (found %r at the top "
                                 "level, %d at any depth, in every spelling): the mirror reads one module file"
                                 % (LIB_SRC, name, top_level_found, anywhere))
    for name, terminator, header, begin, mod_at in items:
        if name in LIB_PINNED_MODS:
            try:
                reject_attributes(masked[begin:mod_at], LIB_SRC, CRATE_DENIED_ATTRIBUTE_WORDS)
            except AssertionError as err:
                raise AssertionError("%s (on the declaration of `mod %s`)" % (err, name))
            if header != LIB_PINNED_MODS[name]:
                raise AssertionError("%s: the declaration of `mod %s` is `%s`, expected `%s` (any other attribute, "
                                     "visibility or body loads other code, compiles it out or hides a second "
                                     "declaration)" % (LIB_SRC, name, header, LIB_PINNED_MODS[name]))
    reject_attributes(masked, LIB_SRC, CRATE_DENIED_ATTRIBUTE_WORDS)
    for found in re.finditer(r"#\s*!\s*\[", masked):
        depth = 0
        for pos in range(found.end() - 1, len(masked)):
            depth += {"[": 1, "]": -1}.get(masked[pos], 0)
            if depth == 0:
                break
        content = compact(lib_clean[found.end():pos])
        if content not in LIB_INNER_ATTRIBUTES:
            raise AssertionError("%s has the inner attribute `#![%s]`, expected only %s: an inner attribute changes "
                                 "how the whole crate resolves names" % (LIB_SRC, content, ", ".join(LIB_INNER_ATTRIBUTES)))
    if re.search(r"(?<![\w'#])include\w*\s*!", masked):
        raise AssertionError("%s uses `include!`: it pulls in code the mirror never reads" % LIB_SRC)
    reject_attributes(masked, LIB_SRC, ("cfg_attr",))
    return tuple(item[:3] for item in items)


@functools.lru_cache(maxsize=64)
def reject_tree_file(rel, clean):
    """Raise when a file of the encryption tree defines a macro, includes code or carries a denied attribute.

    `#[macro_export]` reaches the crate root and a `macro_rules!` with `#[macro_use]` on its module reaches
    mod.rs, so neither is allowed anywhere below src/encryption.
    """
    masked = mask_literals(clean)
    if re.search(r"(?<![\w'#])macro_rules\s*!", masked):
        raise AssertionError("%s defines a `macro_rules!` macro: a macro of the encryption tree can replace one "
                             "the census region invokes" % rel)
    if re.search(r"\binclude\s*!", masked):
        raise AssertionError("%s uses `include!`: it pulls in code the mirror never reads" % rel)
    reject_attributes(masked, rel)
    # r11 code LOW-1: a sibling file below src/encryption is reachable through a re-export chain, so the traits and the
    # top-level macro invocations of the whole tree are pinned per file (none anywhere else).
    traits = [m.group(1) for m in re.finditer(r"(?<![\w'#])trait(?![\w'#])\s*(?:r#)?([A-Za-z_]\w*)", masked)]
    pinned = list(TREE_TRAITS.get(rel, ()))
    for trait in traits:
        if trait not in pinned:
            raise AssertionError("%s declares `trait %s`, which the per-file pin %r does not list: a trait of the "
                                 "encryption tree can be re-exported next to an imported name and add methods the "
                                 "census calls" % (rel, trait, pinned))
    if sorted(traits) != sorted(pinned):
        raise AssertionError("%s declares the traits %r, the per-file pin lists %r: the pin and the file drifted"
                             % (rel, traits, pinned))
    macros = [re.sub(r"\s+", "", m.group(1)) for m in TREE_MACRO.finditer(top_level(masked))]
    if macros != list(TREE_TOP_MACROS.get(rel, ())):
        raise AssertionError("%s invokes the top-level macros %r, expected %r: a macro can emit any item"
                             % (rel, macros, list(TREE_TOP_MACROS.get(rel, ()))))


LIB_MOD_DECL = re.compile(r"(?<![\w'#])mod\s+(?:r#)?([A-Za-z_]\w*)\s*;")


def lib_prefix_modules(lib_clean):
    """Return the names of the `mod NAME;` declarations of src/lib.rs before `mod encryption;` (it excluded)."""
    masked = mask_literals(lib_clean)
    end = masked.index(";", re.search(r"(?<![\w'#])mod\s+(?:r#)?encryption\b", masked).start()) + 1
    return [m.group(1) for m in LIB_MOD_DECL.finditer(masked[:end]) if m.group(1) != "encryption"]


def module_file(name, overrides):
    """Resolve `mod NAME;` of src/lib.rs to its file (`src/NAME.rs` or `src/NAME/mod.rs`); fail closed otherwise."""
    flat, nested = "src/%s.rs" % name, "src/%s/mod.rs" % name
    present = [rel for rel in (flat, nested) if input_exists(rel, overrides)]
    if len(present) != 1:
        raise AssertionError("%s declares `mod %s;` before `mod encryption;` and %d of %s / %s exist: the mirror "
                             "reads every module file the census can see a macro from and fails closed on one "
                             "it cannot resolve" % (LIB_SRC, name, len(present), flat, nested))
    return present[0]


@functools.lru_cache(maxsize=256)
def reject_module_file(rel, text, macros):
    """Raise when a module declared before `mod encryption;` leaks a textual macro the census region invokes.

    `#![macro_use]` as an inner attribute of the module file (any spelling: `cfg_attr`, `r#`, spaces) puts
    the macros the module defines into the crate-root textual scope, so a `macro_rules!` named like one the
    region invokes (`macros`) would replace it inside mod.rs. Without `macro_use` the module's macros stay
    inside it (`#[macro_export]` is path-scoped, not textual).
    """
    if "macro_use" not in text:
        return
    clean = strip_comments(text, rel)
    masked = mask_literals(clean)
    for content, pos in attributes(masked, rel):
        if re.match(r"#\s*!", masked[pos:]) and "macro_use" in IDENT.findall(content):
            raise AssertionError("%s has the inner attribute `#![%s]` naming `macro_use`: the macros the module "
                                 "defines reach the crate-root textual scope, so one the census region invokes "
                                 "could be replaced inside mod.rs" % (rel, re.sub(r"[\s\0]+", "", content)))
    if "macro_use" in masked:
        for name in plain_macros(masked, rel):
            if name in macros:
                raise AssertionError("%s carries `macro_use` and defines the `macro_rules!` macro `%s`, which the "
                                     "census region invokes: it could replace it inside mod.rs" % (rel, name))


