def compact(text):
    """Return `text` with the whitespace OUTSIDE string and char literals removed.

    Whitespace inside a literal is kept, so a trailing space in a pinned literal is a drift.
    """
    masked = mask_literals(text)
    return "".join(ch for ch, mask in zip(text, masked) if not mask.isspace())


def block_end(masked, open_index):
    """Return the index of the `}` that closes the `{` at `open_index` of the literal-masked text."""
    depth = 0
    for pos in range(open_index, len(masked)):
        depth += {"{": 1, "}": -1}.get(masked[pos], 0)
        if depth == 0:
            return pos
    raise AssertionError("%s has a `{` with no closing brace" % RUST_SRC)


def pin_item_before(clean, masked, begin):
    """Pin the item that ends right before the region (#8392): inside `mod tests`, named, nothing between."""
    depth = masked[:begin].count("{") - masked[:begin].count("}")
    if depth != 1:
        raise AssertionError("%s: the census region must sit directly inside `mod tests` (brace depth 1), "
                             "found depth %d" % (RUST_SRC, depth))
    end = len(clean[:begin].rstrip())
    if end == 0 or masked[end - 1] != "}":
        raise AssertionError("%s: the item before the census region must end in `}`, found %r before const %s "
                             "(only whitespace and comments may lie between it and the first constant)"
                             % (RUST_SRC, clean[:begin].rstrip()[-40:], REGION_START))
    depth, opener = 0, -1
    for pos in range(end - 1, -1, -1):
        depth += {"}": 1, "{": -1}.get(masked[pos], 0)
        if depth == 0:
            opener = pos
            break
    if opener < 0:
        raise AssertionError("%s has a `}` with no opening brace before the census region" % RUST_SRC)
    header = compact(clean[max(masked.rfind(c, 0, opener) for c in ";{}") + 1:opener + 1])
    if header != REGION_BEFORE:
        raise AssertionError("%s: the item before the census region is `%s`, expected `%s`: an item inserted "
                             "between them is not pinned by the region table" % (RUST_SRC, header, REGION_BEFORE))


def pin_item_after(clean, end):
    """Pin what follows the region (#8392): only the closing `}` of `mod tests`."""
    tail = compact(clean[end:])
    if not tail.startswith("}"):
        raise AssertionError("%s: the item after the census region is `%s`, expected the closing `}` of "
                             "`mod tests`: an item added inside `mod tests` there is not pinned by the region "
                             "table (an item after the module is a root item, held by the declaration checks)"
                             % (RUST_SRC, tail[:80]))


def census_span(clean):
    """Return (begin, end) of the census region in the stripped source, borders pinned (#8392)."""
    masked = mask_literals(clean)
    declared_once(masked, declaration(REGION_START), "const " + REGION_START)
    declared_once(masked, r"\bfn %s\b" % REGION_LAST_FN, "fn " + REGION_LAST_FN)
    begin = re.search(declaration(REGION_START), masked).start()
    last = re.search(r"\bfn %s\b" % REGION_LAST_FN, masked)
    if last.start() < begin:
        raise AssertionError("%s: fn %s moved above const %s" % (RUST_SRC, REGION_LAST_FN, REGION_START))
    pin_item_before(clean, masked, begin)
    end = block_end(masked, masked.index("{", last.end())) + 1
    pin_item_after(clean, end)
    return begin, end


def census_region(clean):
    """Return the census region of the stripped source, from the first constant to the last test."""
    begin, end = census_span(clean)
    return clean[begin:end]


def chunk_pairs(body):
    """Return (compact, raw) statement chunks of a Rust fragment, split at `;`, `{` and `}`.

    Boundaries are found on the literal-masked text, so a `;`, `{` or `}` inside a literal (raw
    strings included) never splits a chunk and never reads as code. A `;` inside square brackets
    (`[&str; 4]`, `[u8; 2]`) is an array type, not a statement end. `raw` is the uncompacted text.
    """
    masked = mask_literals(body)
    out, begin, brackets = [], 0, 0
    for m in re.finditer(r"[;{}\[\]]", masked):
        brackets += {"[": 1, "]": -1}.get(m.group(0), 0)
        if m.group(0) in "[]" or (m.group(0) == ";" and brackets > 0):
            continue
        out.append((compact(body[begin:m.end()]), body[begin:m.end()]))
        begin = m.end()
    out.append((compact(body[begin:]), body[begin:]))
    return [pair for pair in out if pair[0]]


def chunks(body):
    """Return the compact statement chunks of a Rust fragment (see `chunk_pairs`)."""
    return [chunk for chunk, _ in chunk_pairs(body)]


def pin_chunks(label, got, want, labels=None):
    """Raise AssertionError naming the first chunk of `got` that differs from `want`."""
    for index in range(max(len(got), len(want))):
        have = got[index] if index < len(got) else "<end of body>"
        need = want[index] if index < len(want) else "<end of body>"
        if have != need:
            item = labels[min(index, len(labels) - 1)] if labels else label
            raise AssertionError("%s census region, item `%s`, statement %d changed, the mirror does not "
                                 "follow it: found %r (expected %r)"
                                 % (RUST_SRC, item, index + 1, have, need))


def slotted(chunk, folder):
    """Return `chunk` with the parsed variable parts (constant values, folder, ends_with) slotted."""
    chunk = re.sub(r"^(const(?:%s):).*;$" % "|".join(PARSED_CONSTS), r"\1" + DECL_SLOT + ";",
                   chunk, flags=re.S)
    chunk = re.sub(r'("ls-files","--",)"[^"]+"', r"\1" + FOLDER_SLOT, chunk)
    chunk = chunk.replace("ls-files -- %s`" % folder, "ls-files -- %s`" % FOLDER_SLOT)
    return re.sub(r"if!\((%s(\|\|%s)*)\)\|\|" % (ENDS_TERM, ENDS_TERM),
                  "if!(%s)||" % ENDS_SLOT, chunk, count=1)


CENSUS_IDENT = re.compile(r"(?<!\w)(?:docs_census_|DOCS_CENSUS_)\w*")
# A format string's argument: `{name}` or `{name:spec}` (a spec may nest `{width}`); `{{` and `}}` are escapes.
FORMAT_ARG = re.compile(r"\{\{|\}\}|\{\s*([A-Za-z_]\w*)\s*(?::(?:[^{}]|\{[^{}]*\})*)?\}")


def census_identifiers(clean):
    """Return the census identifiers the Rust compiler resolves: the masked text plus inline format arguments (#8393).

    A `docs_census_` word inside a string literal or a doc comment is text, not a name. The one way a literal
    names an identifier is a format string's inline argument (`format!("{DOCS_CENSUS_X}")`), so the `{name}` and
    `{name:...}` spans of every decoded literal count, `{{` escapes and `\\x7b` spellings included.
    """
    found = set(CENSUS_IDENT.findall(mask_literals(clean)))
    for body in strings(clean):
        for arg in FORMAT_ARG.finditer(body):
            if arg.group(1) is not None and CENSUS_IDENT.fullmatch(arg.group(1)):
                found.add(arg.group(1))
    return found


def close_call_graph(clean):
    """Raise unless every census identifier of the stripped source is pinned and each fn is declared once."""
    masked = mask_literals(clean)
    for name in PINNED_FNS:
        declared_once(masked, r"\bfn %s\b" % name, "fn " + name)
    names = census_identifiers(clean)
    for found, pinned, what in (
            ({n for n in names if n.startswith("docs_census_")}, PINNED_FNS, "docs_census_"),
            ({n for n in names if n.startswith("DOCS_CENSUS_")}, PINNED_CONSTS, "DOCS_CENSUS_")):
        stray = sorted(found - set(pinned))
        if stray:
            raise AssertionError("%s references %s identifiers the mirror does not pin: %s "
                                 "(a new forwarder or helper of the census must be pinned too)"
                                 % (RUST_SRC, what, ", ".join(stray)))


