def compact(text):
    """Return `text` with the whitespace OUTSIDE string and char literals removed.

    Whitespace inside a literal is kept, so a trailing space in a pinned literal is a drift.
    """
    masked = mask_literals(text)
    return "".join(ch for ch, mask in zip(text, masked) if not mask.isspace())


def block_end(masked, open_index):
    """Return the index of the `}` that closes the `{` at `open_index` of the literal-masked text."""
    depth = 0
    for pos in range(open_index, len(masked)):
        depth += {"{": 1, "}": -1}.get(masked[pos], 0)
        if depth == 0:
            return pos
    raise AssertionError("%s has a `{` with no closing brace" % RUST_SRC)


def census_region(clean):
    """Return the census region of the stripped source, from the first constant to the last test."""
    masked = mask_literals(clean)
    declared_once(masked, declaration(REGION_START), "const " + REGION_START)
    declared_once(masked, r"\bfn %s\b" % REGION_LAST_FN, "fn " + REGION_LAST_FN)
    begin = re.search(declaration(REGION_START), masked).start()
    if not clean[:begin].rstrip().endswith("}"):
        raise AssertionError("%s: the census region must start right after the end of the previous "
                             "item, found %r before const %s"
                             % (RUST_SRC, clean[:begin].rstrip()[-40:], REGION_START))
    last = re.search(r"\bfn %s\b" % REGION_LAST_FN, masked)
    if last.start() < begin:
        raise AssertionError("%s: fn %s moved above const %s" % (RUST_SRC, REGION_LAST_FN, REGION_START))
    return clean[begin:block_end(masked, masked.index("{", last.end())) + 1]


def chunk_pairs(body):
    """Return (compact, raw) statement chunks of a Rust fragment, split at `;`, `{` and `}`.

    Boundaries are found on the literal-masked text, so a `;`, `{` or `}` inside a literal (raw
    strings included) never splits a chunk and never reads as code. A `;` inside square brackets
    (`[&str; 4]`, `[u8; 2]`) is an array type, not a statement end. `raw` is the uncompacted text.
    """
    masked = mask_literals(body)
    out, begin, brackets = [], 0, 0
    for m in re.finditer(r"[;{}\[\]]", masked):
        brackets += {"[": 1, "]": -1}.get(m.group(0), 0)
        if m.group(0) in "[]" or (m.group(0) == ";" and brackets > 0):
            continue
        out.append((compact(body[begin:m.end()]), body[begin:m.end()]))
        begin = m.end()
    out.append((compact(body[begin:]), body[begin:]))
    return [pair for pair in out if pair[0]]


def chunks(body):
    """Return the compact statement chunks of a Rust fragment (see `chunk_pairs`)."""
    return [chunk for chunk, _ in chunk_pairs(body)]


def pin_chunks(label, got, want, labels=None):
    """Raise AssertionError naming the first chunk of `got` that differs from `want`."""
    for index in range(max(len(got), len(want))):
        have = got[index] if index < len(got) else "<end of body>"
        need = want[index] if index < len(want) else "<end of body>"
        if have != need:
            item = labels[min(index, len(labels) - 1)] if labels else label
            raise AssertionError("%s census region, item `%s`, statement %d changed, the mirror does not "
                                 "follow it: found %r (expected %r)"
                                 % (RUST_SRC, item, index + 1, have, need))


def slotted(chunk, folder):
    """Return `chunk` with the parsed variable parts (constant values, folder, ends_with) slotted."""
    chunk = re.sub(r"^(const(?:%s):).*;$" % "|".join(PARSED_CONSTS), r"\1" + DECL_SLOT + ";",
                   chunk, flags=re.S)
    chunk = re.sub(r'("ls-files","--",)"[^"]+"', r"\1" + FOLDER_SLOT, chunk)
    chunk = chunk.replace("ls-files -- %s`" % folder, "ls-files -- %s`" % FOLDER_SLOT)
    return re.sub(r"if!\((%s(\|\|%s)*)\)\|\|" % (ENDS_TERM, ENDS_TERM),
                  "if!(%s)||" % ENDS_SLOT, chunk, count=1)


def close_call_graph(clean):
    """Raise unless every census identifier of the stripped source is pinned and each fn is declared once."""
    masked = mask_literals(clean)
    for name in PINNED_FNS:
        declared_once(masked, r"\bfn %s\b" % name, "fn " + name)
    for found, pinned, what in (
            (set(re.findall(r"\bdocs_census_\w*", clean)), PINNED_FNS, "docs_census_"),
            (set(re.findall(r"\bDOCS_CENSUS_\w*", clean)), PINNED_CONSTS, "DOCS_CENSUS_")):
        stray = sorted(found - set(pinned))
        if stray:
            raise AssertionError("%s references %s identifiers the mirror does not pin: %s "
                                 "(a new forwarder or helper of the census must be pinned too)"
                                 % (RUST_SRC, what, ", ".join(stray)))


def pin_region(clean, folder):
    """Pin the whole census region and return the `ends_with` suffixes the census filter reads."""
    close_call_graph(clean)
    pairs = chunk_pairs(census_region(clean))
    got = [slotted(chunk, folder) for chunk, _ in pairs]
    want = [chunk for _, chunks_of in CENSUS_REGION for chunk in chunks_of]
    labels = [label for label, chunks_of in CENSUS_REGION for _ in chunks_of]
    pin_chunks("census region", got, want, labels)
    raw = [raw for (_, raw), chunk in zip(pairs, got) if ENDS_SLOT in chunk]
    if len(raw) != 1:
        raise AssertionError("%s census filter statement not found exactly once" % RUST_SRC)
    return tuple(strings(raw[0]))


def census_folder(clean):
    """Return the folder of the census `git ls-files -- <folder>` call."""
    calls = len(re.findall(r'"ls-files"', clean))
    if calls != 1:
        raise AssertionError('%s must have exactly one `"ls-files"` call site, found %d'
                             % (RUST_SRC, calls))
    match = re.search(r'docs_census_git_on\(\s*root,\s*&\["ls-files",\s*"--",\s*"([^"]+)"\s*\]', clean)
    if match is None:
        raise AssertionError("%s no longer runs `git ls-files -- <folder>` through docs_census_git_on"
                             % RUST_SRC)
    return match.group(1)


def erasable_bytes(clean, scope_clean):
    """Return the sorted `0x..` strings for CRYPTO_ERASABLE_ENVELOPE_VERSIONS (RECORD, SCOPE).

    The census `let bytes` expression is pinned with the rest of the census region. Here the whole
    array is parsed: a `const` (anchored on `const`, with an optional `pub`), declared exactly once
    of any kind, typed `[u8; N]`, every element a constant name declared once as
    `const NAME: u8 = 0x..;` (a numeric literal such as `0x07`, an expression or an unknown name
    raises AssertionError instead of being dropped), N equal to the element count. The result is a
    sorted set: the Rust census result does not depend on the order or on a repeated element.
    """
    declared_once(mask_literals(clean), declaration("CRYPTO_ERASABLE_ENVELOPE_VERSIONS"),
                  "const CRYPTO_ERASABLE_ENVELOPE_VERSIONS")
    match = re.search(r"\b(?:pub(?:\([^)]*\))?\s+)?const\s+CRYPTO_ERASABLE_ENVELOPE_VERSIONS\s*:"
                      r"\s*\[u8;\s*(\d+)\s*\]\s*=\s*\[(.*?)\];", clean, re.S)
    if match is None:
        raise AssertionError("%s no longer declares CRYPTO_ERASABLE_ENVELOPE_VERSIONS as a const [u8; N]"
                             % RUST_SRC)
    elements = [compact(part) for part in match.group(2).split(",")]
    if elements and elements[-1] == "":
        elements.pop()
    if len(elements) != int(match.group(1)) or "" in elements:
        raise AssertionError("%s: CRYPTO_ERASABLE_ENVELOPE_VERSIONS declares [u8; %s] but %d elements "
                             "were parsed: %r" % (RUST_SRC, match.group(1), len(elements), elements))
    masked = mask_literals(clean) + "\n" + mask_literals(scope_clean)
    values = {}
    for src in (clean, scope_clean):
        for name, val in re.findall(r"const ([A-Z_]+_ENVELOPE_VERSION)\s*:\s*u8\s*=\s*0x([0-9a-fA-F]+);",
                                    src):
            values[name] = int(val, 16)
    for element in elements:
        if element not in values:
            raise AssertionError("%s: CRYPTO_ERASABLE_ENVELOPE_VERSIONS element %r is not a known "
                                 "`*_ENVELOPE_VERSION` constant" % (RUST_SRC, element))
        declared_once(masked, declaration(element), "const " + element)
    return sorted({"0x%02x" % values[element] for element in elements})


def rules_entry():
    """Return the walk_guards entry rules.json hands to this mirror."""
