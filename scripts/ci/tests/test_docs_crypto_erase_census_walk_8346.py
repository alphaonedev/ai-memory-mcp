def use_statements(masked):
    """Return [(match, at module level)] for every `use` statement; module level is the file root and `mod` bodies."""
    stack, found, last = [], [], 0
    uses = {m.start(): m for m in USE_STATEMENT.finditer(masked)}
    pos = 0
    while pos < len(masked):
        if pos in uses:
            found.append((uses[pos], all(stack)))
            pos = uses[pos].end()
            continue
        if masked[pos] == "{":
            stack.append(re.search(r"\bmod\s+\w+\s*$", masked[last:pos]) is not None)
            last = pos + 1
        elif masked[pos] == "}":
            if stack:
                stack.pop()
            last = pos + 1
        elif masked[pos] == ";":
            last = pos + 1
        pos += 1
    return found


def module_level_uses(masked):
    """Return the compact `use` statements outside any fn or block: the file root and `mod` bodies."""
    return [compact(match.group(0)) for match, top in use_statements(masked) if top]


def use_bound_names(match):
    """Return the names one `use` statement binds (a glob binds nothing)."""
    tokens = use_tokens(match.group(1))
