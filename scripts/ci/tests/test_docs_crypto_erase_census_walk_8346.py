def reject_bom(text, where):
    """Raise a named error when `text` starts with a UTF-8 byte-order mark (U+FEFF).

    cargo, rustup and rustc skip one leading BOM, the mirror's regexes and TOML reader see it as a character of
    the first line, so a BOM would make the first line (`[package]`, `use ...`) mean something else here than
    there. The guard fails closed instead of stripping: no input file of the census carries a BOM today, so the
    rule costs nothing, and a stripped BOM would be one more silent normalisation (#8346 round 12, code INFO-1
    and security INFO 2: the old message named a line, not the cause).
    """
    if text.startswith("﻿"):
        raise AssertionError("%s starts with a UTF-8 byte-order mark (BOM): cargo, rustup and rustc skip it, the "
                             "mirror would read it as part of the first line, so the file fails closed" % where)
    return text


def read(rel):
    """Return the text of a tracked input file; a missing or unreadable one raises a named AssertionError."""
