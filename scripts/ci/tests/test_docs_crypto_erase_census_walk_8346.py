# The only traits and top-level macro invocations below src/encryption: pinned per file, none anywhere else.
TREE_TRAITS = {"src/encryption/scope/store.rs": ("ScopeKeyStore",)}
TREE_TOP_MACROS = {"src/encryption/scope/tests.rs": ("proptest::proptest",)}

ITEM_HEADER = re.compile(r"(pub(?:\s*\([^)]*\)\s*|\s+))?(?:(?:const|async|unsafe|default)\s+)*"
                         r"(use|fn|struct|enum|union|static|type|impl|mod|trait|extern|macro_rules|const)(?![\w'#])")
ITEM_NAME = re.compile(r"\s*(?:mut\s+)?(?:r#)?([A-Za-z_]\w*)")
TREE_MACRO = re.compile(r"(?<![\w'#:])((?:[A-Za-z_]\w*\s*::\s*)*[A-Za-z_]\w*)\s*!\s*[(\[{]")
ITEM_MACRO = re.compile(r"(?:::\s*)?((?:[A-Za-z_]\w*\s*::\s*)*[A-Za-z_]\w*)\s*!")
BRACE_ITEMS = ("fn", "struct", "enum", "union", "impl", "mod")


def read_attributes(top, pos, rel):
    """Return (next pos, [(inner, content start, content end, attribute start)]) for the attributes at `top[pos]`.

    A bracket-balanced walk (the token tree of an attribute may hold `;`, `{` and `}`), shared by the use-target
    reader and the whole-file src/lib.rs reader; it applies no allow-list.
    """
    spans = []
    while top.startswith("#", pos):
        opener = re.compile(r"#\s*(!?)\s*\[").match(top, pos)
        if opener is None:
            raise AssertionError("%s has a `#` at the top level that is not an attribute the mirror reads" % rel)
        depth, scan = 0, opener.end() - 1
        while True:
            if scan >= len(top):
                raise AssertionError("%s has an attribute that never closes at offset %d" % (rel, pos))
            depth += {"[": 1, "]": -1}.get(top[scan], 0)
            if depth == 0:
                break
            scan += 1
        spans.append((bool(opener.group(1)), opener.end(), scan, pos))
        pos = scan + 1
        while pos < len(top) and top[pos].isspace():
            pos += 1
    return pos, spans


def derive_entries(content):
    """Return the compact full paths of a `derive(...)` attribute content (`zeroize::Zeroize`, `Debug`)."""
    inner = re.sub(r"[\s\0]+", "", content)
    inner = re.sub(r"^(?:r#)?derive\(", "", inner)
    inner = inner[:-1] if inner.endswith(")") else inner
    return [entry.replace("r#", "") for entry in inner.split(",") if entry]


def item_attributes(top, pos, rel):
    """Return (next pos, [attribute content]) for the `#[...]` attributes at `top[pos]`; an unlisted one raises."""
    pos, spans = read_attributes(top, pos, rel)
    found = []
    for inner, start, end, _ in spans:
        if inner:
            raise AssertionError("%s has an inner attribute at the top level: `#![...]` changes how the whole file "
                                 "is read" % rel)
        content = top[start:end]
        head = re.match(r"\s*(?:r#)?([A-Za-z_]\w*)\s*(::)?", content)
        if head is None or head.group(2) or head.group(1) not in TARGET_ATTRIBUTES:
            raise AssertionError("%s has the attribute `#[%s]` on a top-level item: only %s are allow-listed (a "
                                 "path-qualified, `cfg_attr` or unknown attribute can change what the item is)"
                                 % (rel, re.sub(r"[\s\0]+", "", content), "/".join(sorted(TARGET_ATTRIBUTES))))
        if head.group(1) == "derive":
            for entry in derive_entries(content):
                if entry not in TARGET_DERIVES:
                    raise AssertionError("%s derives `%s`: only %s are allow-listed%s (another derive is a proc macro "
                                         "that can emit a trait or an impl)"
                                         % (rel, entry, "/".join(sorted(TARGET_DERIVES)),
                                            ", a path-qualified derive is never allow-listed" if "::" in entry else ""))
        found.append(content)
    return pos, found


def item_end(top, pos, kind, rel):
    """Return the position after the item whose header ends at `pos` (`top` blanks every brace body)."""
    depth = 0
    while pos < len(top):
        char = top[pos]
        if char in "([":
            depth += 1
        elif char in ")]":
            depth -= 1
        elif char == ";" and depth <= 0:
            return pos + 1
        elif char == "{" and depth <= 0:
            close = top.find("}", pos)
            if close < 0:
                raise AssertionError("%s has a `{` with no closing brace" % rel)
            if kind in BRACE_ITEMS:
                return close + 1
            pos = close
        pos += 1
    raise AssertionError("%s has a top-level `%s` item that never ends" % (rel, kind))


IMPL_TOKEN = re.compile(r"->|[<>()\[\]]|(?<![\w'#])for(?![\w'#])")


def split_impl_target(header):
    """Return the target text of an `impl` header (after `impl`): generics and `where` clause removed, the part
    after the last top-level `for` when there is one (`impl<'a> Trait<'a> for Target where ..` gives `Target`)."""
    text = re.split(r"(?<![\w'#])where(?![\w'#])", header)[0].strip()
    depth, begin, last = 0, 0, 0
    for found in IMPL_TOKEN.finditer(text):
        token = found.group(0)
        if token == "->":
            continue
        if token in ("<", "(", "["):
            depth += 1
        elif token in (">", ")", "]"):
            depth -= 1
            if depth == 0 and begin == 0 and text.startswith("<"):
                begin = last = found.end()
        elif depth <= 0:
            last = found.end()
    return text[last:].strip()


def use_item_names(masked, rel):
    """Return the names the `use` statement text `masked` binds (a glob binds none)."""
    match = USE_STATEMENT.fullmatch(masked.strip())
    if match is None:
        raise AssertionError("%s has a `use` statement the mirror cannot parse" % rel)
    bound, _ = use_tree(use_tokens(match.group(1)), 0, [], rel)
    return [name for _, name in bound]


def target_items(rel, masked):
    """Return [(kind, name, header, bound names)] for the top-level items of `masked`; an unlisted shape raises.

    The file is read the way the module system reads it, as an allow-list: every top-level item must be one of
    `use` (never `pub`), `fn`, `struct`, `enum`, `union`, `static`, `const`, `type`, an `impl` whose target is a
    bare struct/enum/union of this file, or a pinned `mod` header. A `trait`, `macro_rules!`, a macro invocation,
    `extern` item or any other shape fails closed, so a shape nobody thought of is rejected instead of passed
    (r11 code LOW-1/LOW-2, security LOW-1: the deny-list of syntax shapes failed review twice on the same class).
    """
    top = top_level(masked)
    items, pos = [], 0
    while True:
        while pos < len(top) and top[pos].isspace():
            pos += 1
        if pos >= len(top):
            break
        begin = pos
        pos, _ = item_attributes(top, pos, rel)
        header = ITEM_HEADER.match(top, pos)
        if header is None:
            macro = ITEM_MACRO.match(top, pos)
            if macro is not None:
                raise AssertionError("%s invokes the macro `%s!` at the top level: a macro can emit any item (a trait, "
                                     "a re-export, a second definition of an imported name)"
                                     % (rel, re.sub(r"\s+", "", macro.group(1))))
            raise AssertionError("%s has a top-level item the allow-list does not name: `%s`"
                                 % (rel, re.sub(r"\s+", " ", top[pos:pos + 48]).strip()))
        kind = header.group(2)
        stop = item_end(top, header.end(), kind, rel)
        text = masked[pos:stop]
        if kind in ("trait", "macro_rules", "extern"):
            name = ITEM_NAME.match(top, header.end())
            if kind == "trait":
                raise AssertionError("%s declares `trait %s`: a trait imported with the pinned `use` line adds methods "
                                     "that method resolution picks ahead of the std ones the census calls"
                                     % (rel, name.group(1) if name else "?"))
            raise AssertionError("%s has a top-level `%s` item: it can emit or rebind any item" % (rel, kind))
        if kind == "use":
            if header.group(1):
                raise AssertionError("%s has the re-export `%s`: a `pub use` can bring in an item named like an "
                                     "imported name, or a trait the importing file then sees"
                                     % (rel, compact(text)))
            items.append(("use", "", compact(text), use_item_names(text, rel)))
        elif kind == "impl":
            brace = top.find("{", header.end(), stop)
            items.append(("impl", "", masked[header.end():brace if brace >= 0 else stop], []))
        else:
            name = ITEM_NAME.match(top, header.end())
            if name is None:
                raise AssertionError("%s has a top-level `%s` item without a name the mirror can read" % (rel, kind))
            head = ""
            if kind == "mod":
                body = top.find("{", header.end(), stop)
                head = compact(masked[begin:(body + 1) if body >= 0 else stop])
            items.append((kind, name.group(1), head, []))
        pos = stop
    return items


# The only `use` bindings of an allow-listed attribute or derive name: the two `zeroize` derives of scope.rs.
USE_NAME_PINS = {SCOPE_SRC: {"Zeroize": ("zeroize", "Zeroize"), "ZeroizeOnDrop": ("zeroize", "ZeroizeOnDrop")}}
GUARDED_NAMES = TARGET_ATTRIBUTES | TARGET_DERIVES | frozenset({"derive", "test"})


def reject_use_bindings(rel, masked):
    """Raise when a `use` of a use-target file binds an allow-listed attribute or derive name (r12 security LOW-1).

    `use other::Hijack as Debug;` makes `#[derive(Debug)]` a proc macro of another crate, `use proc::test;` does the
    same for `#[test]`; the allow-list reads those names as text. Every `use` at any depth is read: a glob, an alias
    to a guarded name, and a binding or last segment that equals a guarded name are rejected, except the pinned
    `zeroize` imports of scope.rs (unaliased). The error names the file and the full binding.
    """
    pins = USE_NAME_PINS.get(rel, {})
    for match in USE_STATEMENT.finditer(masked):
        tokens = use_tokens(match.group(1))
        where = compact(match.group(0))
        if "*" in tokens:
            raise AssertionError("%s has the glob `%s`: a glob use can supply a derive or attribute macro named like "
                                 "an allow-listed one, so a use-target file binds every name explicitly"
                                 % (rel, where))
        for pos, token in enumerate(tokens):
            if token == "as" and tokens[pos + 1] in GUARDED_NAMES:
                raise AssertionError("%s has `%s`, which aliases to the allow-listed attribute or derive name `%s`: "
                                     "the attribute would resolve to the aliased item" % (rel, where, tokens[pos + 1]))
        bound, _ = use_tree(tokens, 0, [], rel)
        for path, name in bound:
            if name in GUARDED_NAMES and not (path[-1] == name and pins.get(name) == tuple(path)):
                raise AssertionError("%s has `%s` that binds `%s` (`%s`): the name is allow-listed as an attribute or "
                                     "derive, a `use` can make it a proc macro of another crate"
                                     % (rel, where, name, "::".join(path)))


def impl_generics(header):
    """Return the names of the generic parameters the `impl` header (after `impl`) declares (lifetimes excluded)."""
    text = header.strip()
    if not text.startswith("<"):
        return set()
    depth, begin, params = 0, 1, []
    for pos, char in enumerate(text):
        if char in "<([":
            depth += 1
        elif char in ">)]" and not (char == ">" and text[pos - 1] == "-"):
            depth -= 1
            if depth == 0:
                params.append(text[begin:pos])
                break
        elif char == "," and depth == 1:
            params.append(text[begin:pos])
            begin = pos + 1
    names = set()
    for param in params:
        found = re.match(r"\s*(?:const\s+)?(?:r#)?([A-Za-z_]\w*)", param)
        if found is not None and not param.strip().startswith("'"):
            names.add(found.group(1))
    return names


def reject_import_target(rel, text, names):
    """Raise unless the module file `rel` cannot change what the imported `names` mean in mod.rs / `mod tests`.

    `use path::{name}` imports every namespace of `name`, so a `trait name` next to the real item, with a blanket impl
    that carries a by-value method (`to_lowercase(self)`, `any(self, ..)`) the census calls, is picked by method
    resolution ahead of the std method while mod.rs stays byte-identical (#8346 round 11, code L1). The file is read
    as an ALLOW-LIST of top-level items (`target_items`): no trait, no macro (declared or invoked), no `include!`, no
    `pub use`, only the pinned `mod` headers, every `impl` on a local type, and each imported name declared exactly
    once of any kind, as the one item kind the pinned `use` line expects. Every error names `rel`.
    """
    masked = mask_literals(strip_comments(text, rel))
    reject_unicode_space(masked, rel)
    if re.search(r"(?<![\w'#])macro_rules\s*!", masked):
        raise AssertionError("%s defines a `macro_rules!` macro: a macro can emit a trait or an item named like an "
                             "imported name" % rel)
    reject_attributes(masked, rel)
    for found in re.finditer(r"(?<![\w'#])trait(?![\w'#])\s*(?:r#)?([A-Za-z_]\w*)?", masked):
        raise AssertionError("%s declares `trait %s`: a trait imported with the pinned `use` line adds methods that "
                             "method resolution picks ahead of the std ones the census calls"
                             % (rel, found.group(1) or "?"))
    if re.search(r"(?<![\w'#])include\w*\s*!", masked):
        raise AssertionError("%s uses `include!`: it pulls in code the mirror never reads" % rel)
    if re.search(r"(?<![\w'#])extern\s+crate\b", masked):
        raise AssertionError("%s contains `extern crate`: it adds a crate to the extern prelude" % rel)
    items = target_items(rel, masked)
    reject_use_bindings(rel, masked)
    local_types = {name for kind, name, _, _ in items if kind in ("struct", "enum", "union")}
    for kind, name, header, _ in items:
        if kind == "mod" and header not in TARGET_MODULES.get(rel, ()):
            raise AssertionError("%s has the module item `%s`, expected one of %r: a nested module inside a use "
                                 "target is not read by the mirror" % (rel, header, TARGET_MODULES.get(rel, ())))
        if kind == "impl":
            target = re.sub(r"\s+", "", split_impl_target(header))
            bare = re.fullmatch(r"(?:r#)?([A-Za-z_]\w*)(?:<.*>)?", target)
            generics = impl_generics(header)
            lead = [tok for tok in re.findall(r"'?[A-Za-z_]\w*", split_impl_target(header)) if not tok.startswith("'")
                    and tok not in ("mut", "const", "dyn", "impl")]
            blanket = ([lead[0]] if lead and lead[0] in generics else
                       [] if bare is not None and bare.group(1) in local_types else
                       sorted(generics & set(IDENT.findall(split_impl_target(header)))))
            if blanket:
                raise AssertionError("%s has `impl%s`, a blanket impl on its own generic parameter `%s`: it applies "
                                     "to every type, std types included, and can add a method the census calls"
                                     % (rel, re.sub(r"\s+", " ", header).strip()[:80], blanket[0]))
            if bare is None or bare.group(1) not in local_types:
                raise AssertionError("%s has `impl%s`: an `impl` in a use-target file must target a struct, enum or "
                                     "union declared in the same file by its bare name (a blanket impl over a generic "
                                     "parameter, a path or a foreign type can add methods to std types)"
                                     % (rel, re.sub(r"\s+", " ", header).strip()[:80]))
    for name in sorted(names):
        if name not in IMPORT_KINDS:
            raise AssertionError("%s is imported by the name `%s`, which the allow-list does not pin: add it to "
                                 "IMPORT_KINDS with its item kind" % (rel, name))
        held = [(kind, name) for kind, found, _, _ in items if found == name and kind != "use"]
        held += [("use", name) for kind, _, _, bound in items if kind == "use" for item in bound if item == name]
        if len(held) != 1:
            raise AssertionError("%s must declare the imported name `%s` exactly once of any kind, found %d (%s)"
                                 % (rel, name, len(held), ", ".join(kind for kind, _ in held) or "none"))
        if held[0][0] != IMPORT_KINDS[name]:
            raise AssertionError("%s declares the imported name `%s` as a `%s`, expected a `%s`: the kind decides "
                                 "which namespace and which trait or method set the importer sees"
                                 % (rel, name, held[0][0], IMPORT_KINDS[name]))


def reject_import_targets(lib_clean, overrides):
    """Read every crate-local module the pinned `use` lines import from (see `local_import_targets`)."""
    for rel, names in sorted(local_import_targets(lib_clean, overrides).items()):
        reject_import_target(rel, read_input(rel, overrides), names)


