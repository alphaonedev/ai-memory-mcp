def generic_names(masked, where=RUST_SRC):
    """Return [("generic", name, position)] for the generic parameters of fn, struct, enum, union, type, trait, impl."""
    found = []
    for owner in GENERIC_OWNER.finditer(masked):
        depth, pos, begin, params = 1, owner.end(), owner.end(), []
        while depth:
            if pos >= len(masked):
                raise AssertionError("%s has a generic parameter list that never closes" % where)
            ch = masked[pos]
            if ch == "<":
                depth += 1
            elif ch == ">" and masked[pos - 1] != "-":
                depth -= 1
            elif ch == "," and depth == 1:
                params.append(masked[begin:pos])
                begin = pos + 1
            pos += 1
        params.append(masked[begin:pos - 1])
        for param in params:
            head = re.match(r"\s*(?:const\s+)?(?:r#)?([A-Za-z_]\w*)", param)
            if head is not None:
                found.append(("generic", head.group(1), owner.start()))
    return found


def declared_names(masked, where=RUST_SRC):
    """Return [(kind, name, position)] for every name an item of ANY kind introduces in the masked source.

    `const`, `static`, `let`, `fn`, `struct`, `enum`, `union`, `type`, `trait`, a `macro_rules!` name and the generic
    parameters (an `r#` prefix is the same name). `mod` items are read by `module_items`, `use` bindings by `use_bindings`.
    """
    found = [(m.group(1), m.group(2), m.start()) for m in ITEM_DECL.finditer(masked)]
    found += [("static", m.group(1), m.start()) for m in STATIC_REF_DECL.finditer(masked)]
    found += [("macro_rules!", m.group(1), m.start()) for m in MACRO_DECL.finditer(masked)]
    return found + generic_names(masked, where)


def declaration(name):
    """Return a regex for a `const`, `static` or `let` declaration of `name` (the region start anchor)."""
    return r"\b(?:const|static|let)\s+(?:mut\s+)?%s\b" % re.escape(name)


def declared_once(masked, pattern, what):
    """Raise unless `pattern` occurs exactly once in the literal-masked, comment-stripped source."""
    count = len(re.findall(pattern, masked))
    if count != 1:
        raise AssertionError("%s must declare %s exactly once in live code, found %d"
                             % (RUST_SRC, what, count))


# `\s*` after `pub(...)` and after `use`: `pub(crate)use` and `use{a}` are valid Rust (r11 probes N8b, N9).
USE_STATEMENT = re.compile(r"(?:(?<![\w'#])pub(?:\s*\([^)]*\))?\s*)?(?<![\w'#])use(?![\w'#])\s*([^;]*);")
USE_TOKEN = re.compile(r"::|[{},*]|(?:r#)?[A-Za-z_]\w*")


def use_tokens(text):
    """Return the tokens of a use tree with every raw-identifier `r#` prefix stripped (r12 code INFO-2).

    `use x as r#env_lock` binds `env_lock`: rustc reads `r#name` as the same identifier as `name`.
    """
    return [tok[2:] if tok.startswith("r#") else tok for tok in USE_TOKEN.findall(text)] + [""] * 3


# The one legitimate `use` binding of a parsed constant: the pinned `pub use scope::{...}` re-export.
REEXPORT_PATH_ROOT = "scope"


def use_tree(tokens, pos, prefix, where=RUST_SRC):
    """Return ([(path, bound name)], next pos) for the use tree at `tokens[pos]` (globs bind nothing)."""
    path = list(prefix)
    while True:
        tok = tokens[pos]
        if tok == "::":
            pos += 1
        elif tok == "{":
            pos, found = pos + 1, []
            while tokens[pos] != "}":
                sub, pos = use_tree(tokens, pos, path, where)
                found += sub
                pos += 1 if tokens[pos] == "," else 0
            return found, pos + 1
        elif tok == "*":
            return [], pos + 1
        elif tok in ("", ",", "}"):
            raise AssertionError("%s has a `use` statement the mirror cannot parse" % where)
        elif tokens[pos + 1] == "as":
            return [(path + [tok], tokens[pos + 2])], pos + 3
        elif tokens[pos + 1] == "::":
            path.append(tok)
            pos += 1
        else:
            return [(path + [tok], path[-1] if tok == "self" and path else tok)], pos + 1


def use_bindings(masked, name, where=RUST_SRC, reexport_ok=True):
    """Return the compact `use` statements of the literal-masked source that bind `name`.

    `use a::b as NAME`, `use a::NAME`, `use a::{x, NAME}` and `use a::{b as NAME}` all bind `NAME`; a
    glob binds nothing. In src/encryption/mod.rs (`reexport_ok`) the pinned unaliased re-export `scope::NAME`
    is the same declaration, not a second; in every other file it is a binding like any other (r11 code LOW-1:
    the exemption must never hide a re-export in a use-target file).
    """
    hits = []
    for match in USE_STATEMENT.finditer(masked):
        tokens = use_tokens(match.group(1))
        bound, _ = use_tree(tokens, 0, [], where)
        for path, bound_name in bound:
            reexport = (reexport_ok and path[:1] == [REEXPORT_PATH_ROOT] and len(path) == 2
                        and path[-1] == bound_name)
            if bound_name == name and not reexport:
                hits.append(compact(match.group(0)))
    return hits


def declared_name_once(masked, name, what, where=RUST_SRC):
    """Raise unless `name` has exactly one declaration (ANY item kind) or `use` binding in the masked, stripped source."""
    declared = len([found for found in declared_names(masked) if found[1] == name])
    bindings = use_bindings(masked, name)
    if declared + len(bindings) != 1:
        raise AssertionError("%s must declare %s exactly once in live code, found %d (%d declaration(s) "
                             "and %d `use` binding(s): %s)" % (where, what, declared + len(bindings),
                                                                declared, len(bindings), "; ".join(bindings)))


ESCAPE = re.compile(r"\\(?:x([0-7][0-9a-fA-F])|u\{([0-9a-fA-F_]{1,13})\}|([nrt0\\'\"])|\n[ \t\r\n]*)")
SIMPLE_ESCAPES = {"n": "\n", "r": "\r", "t": "\t", "0": "\0", "\\": "\\", "'": "'", '"': '"'}


def unescape(literal):
    """Decode the escapes of a plain Rust string literal body; any other backslash raises."""
    def decode(m):
        if m.group(1) is not None:
            return chr(int(m.group(1), 16))
        if m.group(2) is not None:
            return chr(int(m.group(2).replace("_", ""), 16))
        if m.group(3) is not None:
            return SIMPLE_ESCAPES[m.group(3)]
        return ""
    if "\\" in ESCAPE.sub("", literal):
        raise AssertionError("%s has a string literal with an escape the mirror cannot decode: %r"
                             % (RUST_SRC, literal))
    return ESCAPE.sub(decode, literal)


def strings(body):
    """Return the string literals (plain and raw) of a Rust fragment, in order, comments excluded.

    Plain literals are decoded (an `x2d` hex escape, a `u{5f}` escape, the simple escapes, a backslash-newline
    continuation), so the mirror holds the Rust value, not its spelling; a raw string is taken as
    written, and a backslash the decoder does not know raises AssertionError.
    """
    found = []
    for m in RUST_TOKEN.finditer(body):
        if m.group("str") is not None:
            found.append(unescape(m.group("str")[1:-1]))
        elif m.group("raw") is not None:
            found.append(re.fullmatch(r'[bc]?r(#*)"(.*)"\1', m.group("raw"), re.S).group(2))
    return found


def masked_matches(clean, pattern, flags=0):
    """Return the matches of `pattern` on the LITERAL-MASKED text (a string literal never matches).

    The masked text has the length of `clean`, so a group's span slices the value text out of the unmasked source
    (`clean[m.start(1):m.end(1)]`). A declaration-shaped string literal (a decoy, plain or raw) is therefore invisible
    to every value reader, the same way it is invisible to the declared-once checks (#8346 round 10, security L1).
    """
    return list(re.finditer(pattern, mask_literals(clean), flags))


def one_match(clean, pattern, what, flags=0, where=RUST_SRC):
    """Return the single masked match of `pattern`; zero or several raise AssertionError naming `what`."""
    found = masked_matches(clean, pattern, flags)
    if len(found) != 1:
        raise AssertionError("%s must declare %s exactly once in live code (outside any string literal) for the "
                             "value reader, found %d" % (where, what, len(found)))
    return found[0]


def const_body(clean, name):
    """Return the body of `const <name>: ... = ...;` (masked search, unmasked slice; exactly one declaration)."""
    pattern = r"const %s\s*:[^=]*=\s*(.*?);\n" % re.escape(name)
    if not masked_matches(clean, pattern, re.S):
        raise AssertionError("%s no longer declares %s" % (RUST_SRC, name))
    match = one_match(clean, pattern, "const " + name, re.S)
    return clean[match.start(1):match.end(1)]


def const_len(clean, name):
    """Return N from the declared type `const <name>: [&str; N]` (masked search, exactly one declaration)."""
    pattern = r"const %s\s*:\s*\[&str;\s*(\d+)\s*\]" % re.escape(name)
    if not masked_matches(clean, pattern):
        raise AssertionError("%s no longer declares %s as [&str; N]" % (RUST_SRC, name))
    match = one_match(clean, pattern, "const %s: [&str; N]" % name)
    return int(clean[match.start(1):match.end(1)])


def string_list(clean, name):
    """Return the string literals of const <name>; fail unless there are exactly N."""
    found = strings(const_body(clean, name))
    declared = const_len(clean, name)
    if len(found) != declared:
        raise AssertionError("%s: %s declares [&str; %d] but %d plain string literals were parsed"
                             % (RUST_SRC, name, declared, len(found)))
    return found


