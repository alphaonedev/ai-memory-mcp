def generic_names(masked):
    """Return [("generic", name, position)] for the generic parameters of fn, struct, enum, union, type, trait, impl."""
    found = []
    for owner in GENERIC_OWNER.finditer(masked):
        depth, pos, begin, params = 1, owner.end(), owner.end(), []
        while depth:
            if pos >= len(masked):
                raise AssertionError("%s has a generic parameter list that never closes" % RUST_SRC)
            ch = masked[pos]
            if ch == "<":
                depth += 1
            elif ch == ">" and masked[pos - 1] != "-":
                depth -= 1
            elif ch == "," and depth == 1:
                params.append(masked[begin:pos])
                begin = pos + 1
            pos += 1
        params.append(masked[begin:pos - 1])
        for param in params:
            head = re.match(r"\s*(?:const\s+)?(?:r#)?([A-Za-z_]\w*)", param)
            if head is not None:
                found.append(("generic", head.group(1), owner.start()))
    return found


def declared_names(masked):
    """Return [(kind, name, position)] for every name an item of ANY kind introduces in the masked source.

    `const`, `static`, `let`, `fn`, `struct`, `enum`, `union`, `type`, `trait`, a `macro_rules!` name and the generic
    parameters (an `r#` prefix is the same name). `mod` items are read by `module_items`, `use` bindings by `use_bindings`.
    """
    found = [(m.group(1), m.group(2), m.start()) for m in ITEM_DECL.finditer(masked)]
    found += [("macro_rules!", m.group(1), m.start()) for m in MACRO_DECL.finditer(masked)]
    return found + generic_names(masked)


def declaration(name):
    """Return a regex for a `const`, `static` or `let` declaration of `name` (the region start anchor)."""
    return r"\b(?:const|static|let)\s+(?:mut\s+)?%s\b" % re.escape(name)


def declared_once(masked, pattern, what):
    """Raise unless `pattern` occurs exactly once in the literal-masked, comment-stripped source."""
    count = len(re.findall(pattern, masked))
    if count != 1:
        raise AssertionError("%s must declare %s exactly once in live code, found %d"
                             % (RUST_SRC, what, count))


USE_STATEMENT = re.compile(r"(?:\bpub(?:\s*\([^)]*\))?\s+)?\buse\s+([^;]*);")
USE_TOKEN = re.compile(r"::|[{},*]|[A-Za-z_]\w*")
# The one legitimate `use` binding of a parsed constant: the pinned `pub use scope::{...}` re-export.
REEXPORT_PATH_ROOT = "scope"


def use_tree(tokens, pos, prefix):
    """Return ([(path, bound name)], next pos) for the use tree at `tokens[pos]` (globs bind nothing)."""
    path = list(prefix)
    while True:
        tok = tokens[pos]
        if tok == "::":
            pos += 1
        elif tok == "{":
            pos, found = pos + 1, []
            while tokens[pos] != "}":
                sub, pos = use_tree(tokens, pos, path)
                found += sub
                pos += 1 if tokens[pos] == "," else 0
            return found, pos + 1
        elif tok == "*":
            return [], pos + 1
        elif tok in ("", ",", "}"):
            raise AssertionError("%s has a `use` statement the mirror cannot parse" % RUST_SRC)
        elif tokens[pos + 1] == "as":
            return [(path + [tok], tokens[pos + 2])], pos + 3
        elif tokens[pos + 1] == "::":
            path.append(tok)
            pos += 1
        else:
            return [(path + [tok], path[-1] if tok == "self" and path else tok)], pos + 1


def use_bindings(masked, name):
    """Return the compact `use` statements of the literal-masked source that bind `name`.

    `use a::b as NAME`, `use a::NAME`, `use a::{x, NAME}` and `use a::{b as NAME}` all bind `NAME`; a
    glob binds nothing. The pinned unaliased re-export `scope::NAME` is the same declaration, not a second.
    """
    hits = []
    for match in USE_STATEMENT.finditer(masked):
        tokens = USE_TOKEN.findall(match.group(1)) + [""] * 3
        bound, _ = use_tree(tokens, 0, [])
        for path, bound_name in bound:
            reexport = path[:1] == [REEXPORT_PATH_ROOT] and len(path) == 2 and path[-1] == bound_name
            if bound_name == name and not reexport:
                hits.append(compact(match.group(0)))
    return hits


