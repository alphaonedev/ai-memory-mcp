OWN_TYPE_USES_OUTSIDE_REGION = 0
# What may stand in front of the type path of an `impl` target: `(`, `&`, a lifetime, `mut`, `dyn`, a raw pointer, `::`.
IMPL_TARGET_PREFIX = re.compile(r"\s*(?:\(|&|'\w+|mut\b|dyn\b|\*\s*(?:const|mut)\b|::)")
IMPL_TARGET_PATH = re.compile(r"\s*(?:[A-Za-z_]\w*\s*::\s*)*([A-Za-z_]\w*)")


def impl_target(target):
    """Return the match whose group 1 is the last path segment naming an `impl` target, `r#` and parentheses removed.

    `r#DocsCensus`, `r#self::DocsCensus`, `(DocsCensus)` and `((&DocsCensus))` all name the same type as the plain
    spelling, so they are normalised before the name is read (#8346 round 11, security L-A).
    """
    target = re.sub(r"(?<!\w)r#(?=[A-Za-z_])", "", target)
    while True:
        prefix = IMPL_TARGET_PREFIX.match(target)
        if prefix is None:
            break
        target = target[prefix.end():]
    return IMPL_TARGET_PATH.match(target)


def derive_external_names(region_masked, masked, region_text=""):
    """Return the names the census region resolves outside itself, DERIVED from its text and the pinned imports.

    Every identifier of the region that is not a keyword and not declared inside the region itself (path roots,
    types, traits, macros, functions and methods it calls; a name the region declares is held by the declared-once
    and call-graph checks), the inline format arguments of its string literals (`{rel}` is an identifier the compiler
    resolves although the literal is masked), the names the module-level `use`
    lines bind (they are what `use super::*` hands `mod tests`) and the crate roots `std`, `core`, `alloc`.
    """
    # `let Some(x)` names the prelude variant `Some`, it declares nothing: only a lowercase `let` name is a binding.
    own = {name for kind, name, _ in declared_names(region_masked) if kind != "let" or name[0].islower()}
    names = {word for word in IDENT.findall(region_masked) if word not in KEYWORDS and word != "_"}
    names = (names | {arg for arg in format_arguments(region_text) if arg not in KEYWORDS}) - own
    for match, top in use_statements(masked):
        if top:
            names.update(use_bound_names(match))
    return frozenset(names | {"std", "core", "alloc"})


def reject_shadowing(clean, span):
    """Raise when an item of any kind outside the region, or a local `use`, is named like an external name.

    A name introduced by an item shadows the std item the region means (`struct String;`, `type Vec<T> = ..`,
    `fn contains`): the pinned region text then resolves to local code. Returns (external names, region macros).
    A generic parameter or a `let` only shadows inside its own item or block, never inside the region, so
    neither is compared; a `mod` item is held by `pin_modules`; the module-level `use` lines are pinned.
    """
    masked = mask_literals(clean)
    region_masked = masked[span[0]:span[1]]
    external = derive_external_names(region_masked, masked, clean[span[0]:span[1]])
    if len(external) != EXTERNAL_NAMES_COUNT:
        raise AssertionError("%s: derived external names: found %d, pinned %d (a census region edit that adds or "
                             "drops a name it resolves outside itself must be reviewed against the item names "
                             "of mod.rs, then EXTERNAL_NAMES_COUNT updated): %s"
                             % (RUST_SRC, len(external), EXTERNAL_NAMES_COUNT, ", ".join(sorted(external))))
    for kind, name, pos in declared_names(masked):
        if kind in ("let", "generic") or span[0] <= pos < span[1] or name in OUTSIDE_RESOLVED:
            continue
        if name in external:
            raise AssertionError("%s declares a `%s` named `%s`, a name the census region resolves outside "
                                 "itself: the pinned region text would then mean local code, not the std item"
                                 % (RUST_SRC, kind, name))
    for match, top in use_statements(masked):
        for name in use_bound_names(match):
            if not top and name in external:
                raise AssertionError("%s has a function-local `use` binding of `%s`, a name the census region "
                                     "resolves outside itself" % (RUST_SRC, name))
    # the types the region declares: an `impl` of one outside the region runs code inside the pinned census
    # (`impl Drop for DocsCensus` fires when the pinned test drops the value, #8346 round 10 code L2)
    own_types = {name for kind, name, _ in declared_names(region_masked) if kind in OWN_TYPE_KINDS}
    # an `impl` ITEM starts a statement (`impl Trait` in an argument or return type does not)
    for head in re.finditer(r"(?:^|[;{}\]])\s*(?:unsafe\s+)?impl\b([^{;]*)", masked):
        generics = {name for kind, name, pos in generic_names(masked[head.start():head.end()])}
        text = head.group(1)
        text = text[text.index(">") + 1:] if text.lstrip().startswith("<") and ">" in text else text
        named = impl_target(re.split(r"\bfor\b(?!\s*<)", text)[-1])
        if named is not None and named.group(1) in own_types and not span[0] <= head.start() < span[1]:
            raise AssertionError("%s has an `impl` for `%s` outside the census region, a type the region declares: "
                                 "an inherent or trait impl (`Drop`) runs code inside the pinned census"
                                 % (RUST_SRC, named.group(1)))
        if named is not None and (named.group(1) in external or named.group(1) in generics):
            raise AssertionError("%s has an `impl ... for` `%s`, a name the census region resolves outside itself "
                                 "(or a blanket impl over a generic parameter)" % (RUST_SRC, named.group(1)))
    # Stricter form (the live count is OWN_TYPE_USES_OUTSIDE_REGION = 0, so no allow-list is needed): an own-type
    # identifier ANYWHERE outside the region, raw (`r#DocsCensus`) or plain, is rejected. A `type Alias = DocsCensus;`
    # or `use DocsCensus as Other;` outside the region followed by `impl Drop for Alias` runs code in the census
    # through a name the impl-target scan never sees (#8346 round 11, security L-A).
    for name in sorted(own_types):
        for use in re.finditer(r"(?<!\w)%s\b" % re.escape(name), masked):
            if not span[0] <= use.start() < span[1]:
                raise AssertionError("%s names the type `%s` the census region declares outside the region (an alias, "
                                     "a path or an impl target): the type may only be named by the region itself"
                                     % (RUST_SRC, name))
    return external, region_macros(region_masked)


def pin_imports(clean):
    """Pin the exact module-level `use` lines (mod.rs root and `mod tests`), `pub use scope::{...}` included."""
    got = module_level_uses(mask_literals(clean))
    for index in range(max(len(got), len(USE_SURFACE))):
        have = got[index] if index < len(got) else "<end of imports>"
        need = USE_SURFACE[index] if index < len(USE_SURFACE) else "<end of imports>"
        if have != need:
            raise AssertionError("%s import surface changed at `use` statement %d, a rename here changes which "
                                 "item a census name resolves to: found %r (expected %r)"
                                 % (RUST_SRC, index + 1, have, need))


def pin_region(clean, folder):
    """Pin the whole census region and return the `ends_with` suffixes the census filter reads."""
    close_call_graph(clean)
    pairs = chunk_pairs(census_region(clean))
    got = [slotted(chunk, folder) for chunk, _ in pairs]
    want = [chunk for _, chunks_of in CENSUS_REGION for chunk in chunks_of]
    labels = [label for label, chunks_of in CENSUS_REGION for _ in chunks_of]
    pin_chunks("census region", got, want, labels)
    raw = [raw for (_, raw), chunk in zip(pairs, got) if ENDS_SLOT in chunk]
    if len(raw) != 1:
        raise AssertionError("%s census filter statement not found exactly once" % RUST_SRC)
    return tuple(strings(raw[0]))


def census_git_args(clean):
    """Return the argument literals of the census `git ls-files ... -- <folder>` call, `ls-files` first."""
    calls = len(re.findall(r'"ls-files"', clean))
    if calls != 1:
        raise AssertionError('%s must have exactly one `"ls-files"` call site, found %d'
                             % (RUST_SRC, calls))
    match = re.search(r'docs_census_git_on\(\s*root,\s*&\[\s*("ls-files"(?:\s*,\s*"[^"]*")*)\s*,?\s*\]', clean)
    if match is None:
        raise AssertionError("%s no longer runs `git ls-files -- <folder>` through docs_census_git_on"
                             % RUST_SRC)
    args = tuple(strings(match.group(1)))
    if "--" not in args or args.index("--") != len(args) - 2:
        raise AssertionError("%s: the `ls-files` call is not `... -- <folder>`: %r" % (RUST_SRC, args))
    return args


def census_folder(clean):
    """Return the folder of the census `git ls-files -- <folder>` call."""
    return census_git_args(clean)[-1]


