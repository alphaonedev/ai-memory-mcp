"""Loaded-origin helper for the cf-dashboard CSP guard (#7313); imported by test_cf_dashboard_7313.py.

The origin of a URL is computed by a small, closed re-implementation of the WHATWG URL parser (host,
port, userinfo, IPv4/IPv6, percent-decoding, IDNA) for the two network schemes a page can load from,
http and https. The guard FAILS CLOSED (#7512): a value the parser cannot parse is reported as the
sentinel `unparsed:<value>`, which is never in a CSP allow-set, so the check goes red instead of
silently dropping a URL the browser might still load. The parser is pinned to the browser by
fixtures/whatwg_origin_cases_7313.json (recorded from `new URL`, regenerated by the script beside it).

Beyond network origins the guard also sees what a page loads from itself (#7589: page-relative URLs, `data:`
and `blob:` are matched against `'self'` and scheme sources), what CSS pulls in (#7590: style attributes,
`<style>` bodies, `@import`, `@font-face`, the legacy `background` attribute), inline script and style
(elements and attributes), and every policy a page gets (#7591: each header line and each `<meta http-equiv>`
policy is enforced independently; a load must pass all of them).
"""
import collections
import ipaddress
import re
import unicodedata
import urllib.parse
from html.parser import HTMLParser

URL_ATTRS = ("src", "href", "data", "poster", "xlink:href")
NON_LOADING_RELS = frozenset(("preconnect", "dns-prefetch"))
DEFAULT_PORTS = {"https": "443", "http": "80"}
PAGE_SCHEME = "https"  # the dashboard is served over https; a same-scheme `https:path` is page-relative
C0_AND_SPACE = "".join(chr(i) for i in range(0x21))
MAX_PORT = 65535
UNPARSED_PREFIX = "unparsed:"
SELF_ORIGIN = "'self'"    # a page-relative load (the quotes keep it from ever being a scheme)
INLINE_ORIGIN = "'inline'"  # inline script / style and event handlers
DATA_ORIGIN = "data:"
BLOB_ORIGIN = "blob:"
NON_NETWORK_ORIGINS = frozenset((SELF_ORIGIN, INLINE_ORIGIN, DATA_ORIGIN, BLOB_ORIGIN))

_SCHEME_RE = re.compile(r"^([A-Za-z][A-Za-z0-9+.\-]*):")
_PORT_RE = re.compile(r"^[0-9]*$")
_FORBIDDEN_HOST_CHARS = frozenset(" #%/:<>?@[\\]^|\x7f") | frozenset(chr(i) for i in range(0x20))
# UTS #46 (what browsers run) and the IDNA2003 codec Python ships disagree on these; refuse them (fail closed)
_IDNA_DIVERGENT = frozenset("\u00df\u03c2\u03f2\u200c\u200d")


class UnparsedURL(ValueError):
    """The value is a network URL (or looks like one) that the WHATWG parser would reject or that this
    parser cannot prove it understands. The caller must treat it as a guard failure."""


def _ipv4_number(part):
    """WHATWG IPv4 number parser: the value, or None on failure."""
    if part == "":
        return None
    radix = 10
    if len(part) >= 2 and part[:2].lower() == "0x":
        part, radix = part[2:], 16
    elif len(part) >= 2 and part[0] == "0":
        part, radix = part[1:], 8
    if part == "":
        return 0
    digits = "0123456789abcdef"[:radix]
    if any(ch not in digits for ch in part.lower()):
        return None
    return int(part, radix)


def _ends_in_number(host):
    parts = host.split(".")
    if parts[-1] == "":
        if len(parts) == 1:
            return False
        parts.pop()
    last = parts[-1]
    if last and re.fullmatch(r"[0-9]+", last):
        return True
    return _ipv4_number(last) is not None


def _ipv4(host):
    parts = host.split(".")
    if parts[-1] == "" and len(parts) > 1:
        parts.pop()
    if len(parts) > 4:
        raise UnparsedURL("IPv4 host with more than four parts")
    nums = []
    for part in parts:
        num = _ipv4_number(part)
        if num is None:
            raise UnparsedURL("IPv4 host with a non-numeric part")
        nums.append(num)
    if any(n > 255 for n in nums[:-1]) or nums[-1] >= 256 ** (5 - len(nums)):
        raise UnparsedURL("IPv4 host out of range")
    value = nums[-1] + sum(n * 256 ** (3 - i) for i, n in enumerate(nums[:-1]))
    return ".".join(str((value >> shift) & 255) for shift in (24, 16, 8, 0))


def _ipv6(inner):
    """Serialise an IPv6 literal like the WHATWG serializer ([::1], first longest zero run compressed)."""
    if not re.fullmatch(r"[0-9A-Fa-f:.]+", inner):
        raise UnparsedURL("invalid IPv6 literal")
    try:
        value = int(ipaddress.IPv6Address(inner))
    except ValueError as exc:
        raise UnparsedURL("invalid IPv6 literal") from exc
    pieces = [(value >> (112 - 16 * i)) & 0xFFFF for i in range(8)]
    best_start, best_len, i = -1, 0, 0
    while i < 8:
        if pieces[i] != 0:
            i += 1
            continue
        j = i
        while j < 8 and pieces[j] == 0:
            j += 1
        if j - i > best_len:
            best_start, best_len = i, j - i
        i = j
    if best_len < 2:
        best_start = -1
    out, i = [], 0
    while i < 8:
        if i == best_start:
            out.append("::" if i == 0 else ":")
            i += best_len
            continue
        out.append("%x" % pieces[i])
        if i != 7:
            out.append(":")
        i += 1
    return "[" + "".join(out) + "]"


_LABEL_DOTS = re.compile("[.\u3002\uff0e\uff61]")
_UNASSIGNED = frozenset(("Cn", "Co", "Cs"))


def _check_labels(unicode_host):
    """UTS 46 validity the IDNA2003 codec does not enforce (#7546): a label must not begin with a combining mark
    (general category M) and must not contain an unassigned, private-use or surrogate code point. Applied to
    typed Unicode labels and to the decoded form of every `xn--` label. Unassigned is judged by this Python's
    Unicode data, which can be older than the browser's: that errs towards `unparsed`, never towards a host."""
    for label in _LABEL_DOTS.split(unicode_host):
        if label and unicodedata.category(label[0]).startswith("M"):
            raise UnparsedURL("host label begins with a combining mark")
        if any(unicodedata.category(ch) in _UNASSIGNED for ch in label):
            raise UnparsedURL("host label contains an unassigned code point")


def _domain(raw):
    """Percent-decode, lower-case and IDNA-encode a host, reject forbidden code points, canonicalise IPv4."""
    try:
        host = urllib.parse.unquote_to_bytes(raw).decode("utf-8")
    except UnicodeDecodeError as exc:
        raise UnparsedURL("host is not valid UTF-8 after percent-decoding") from exc
    if not host.isascii():
        if _IDNA_DIVERGENT & set(host):
            raise UnparsedURL("host uses a character whose IDNA mapping differs between UTS 46 and IDNA 2003")
        host = unicodedata.normalize("NFKC", host).lower()
        _check_labels(host)
        try:
            host = host.encode("idna").decode("ascii")
        except UnicodeError as exc:
            raise UnparsedURL("host is not valid IDNA") from exc
    host = host.lower()
    if host == "":
        raise UnparsedURL("empty host")
    if _FORBIDDEN_HOST_CHARS & set(host):
        raise UnparsedURL("host contains a forbidden code point")
    if any(label.startswith("xn--") for label in host.split(".")):
        try:
            decoded = host.encode("ascii").decode("idna")
        except UnicodeError as exc:
            raise UnparsedURL("host has an invalid punycode label") from exc
        _check_labels(decoded)
    if _ends_in_number(host):
        return _ipv4(host)
    return host


def normalise_url(value):
    """WHATWG pre-parse: strip leading/trailing C0 controls and space, drop tab/LF/CR, treat `\\` as `/`."""
    value = value.strip(C0_AND_SPACE)
    return re.sub(r"[\t\n\r]", "", value).replace("\\", "/")


def _resolve_path(path):
    """Resolve `.` and `..` segments (also their `%2e` spellings) like the WHATWG path state."""
    segments = path.split("/")[1:]
    out = []
    for index, segment in enumerate(segments):
        last = index == len(segments) - 1
        low = segment.lower()
        if low in (".", "%2e"):
            if last:
                out.append("")
            continue
        if low in ("..", ".%2e", "%2e.", "%2e%2e"):
            if out:
                out.pop()
            if last:
                out.append("")
            continue
        out.append(segment)
    return "/" + "/".join(out)


def parse_url(value):
    """(origin, path) of an http(s) or protocol-relative URL, or None for anything that loads nothing from
    another network origin (page-relative, `data:`, `javascript:`, any non-http(s) scheme). The origin is
    `scheme://host[:port]` (lower-case, default port dropped); the path has dot segments resolved and no
    query or fragment (`/` when empty). Raises UnparsedURL for a network URL that does not parse."""
    text = normalise_url(value)
    match = _SCHEME_RE.match(text)
    if match:
        scheme = match.group(1).lower()
        rest = text[match.end():]
        if scheme not in DEFAULT_PORTS:
            return None
        if scheme == PAGE_SCHEME and not rest.startswith("//"):
            return None  # `https:path` and `https:/path` resolve against the page
    elif text.startswith("//"):
        scheme, rest = PAGE_SCHEME, text
    else:
        return None
    rest = rest.lstrip("/")  # the special-authority states skip every leading slash
    authority = rest[:re.search(r"[/?#]|$", rest).start()]
    target = re.split(r"[?#]", rest[len(authority):], maxsplit=1)[0]
    path = _resolve_path(target if target.startswith("/") else "/" + target)
    hostport = authority[authority.rfind(chr(64)) + 1:]  # userinfo ends at the LAST at-sign
    if hostport.startswith("["):
        close = hostport.find("]")
        if close < 0:
            raise UnparsedURL("unterminated IPv6 literal")
        host, tail = _ipv6(hostport[1:close]), hostport[close + 1:]
        if tail and not tail.startswith(":"):
            raise UnparsedURL("text after the IPv6 literal")
        port = tail[1:]
    else:
        raw_host, _, port = hostport.partition(":")
        host = _domain(raw_host)
    if not _PORT_RE.match(port):
        raise UnparsedURL("port is not a number")
    port = str(int(port)) if port else ""
    if port and int(port) > MAX_PORT:
        raise UnparsedURL("port out of range")
    suffix = "" if not port or port == DEFAULT_PORTS[scheme] else ":" + port
    return "%s://%s%s" % (scheme, host, suffix), path


def parse_origin(value):
    """Origin of a URL as `parse_url` reads it, or None when it loads nothing from another network origin."""
    parsed = parse_url(value)
    return parsed[0] if parsed else None


def resolve_load(value):
    """(origin, path) of anything a URL attribute or CSS url() can load, or None when it loads nothing: network
    origins as `parse_url`; a page-relative URL is SELF_ORIGIN; `data:` and `blob:` are their scheme; a fragment-only
    URL, an empty value and every other scheme (`javascript:`, `about:`, `mailto:`) load nothing here.
    Raises UnparsedURL for a network URL that does not parse."""
    text = normalise_url(value)
    if text == "" or text.startswith("#"):
        return None
    match = _SCHEME_RE.match(text)
    if match:
        scheme = match.group(1).lower()
        if scheme in ("data", "blob"):
            return scheme + ":", ""
        parsed = parse_url(value)
        if parsed is None:
            return (SELF_ORIGIN, "/") if scheme == PAGE_SCHEME else None
        return parsed
    return parse_url(value) or (SELF_ORIGIN, "/")


# A loaded resource: `kind` is the fetch kind the browser checks (a key of CHAINS), `origin` is the normalised
# origin (or `unparsed:<value>`), `path` the resolved URL path, `nonce` the element's nonce attribute.
Load = collections.namedtuple("Load", "kind origin path nonce")

# kind -> the CSP3 fallback chain of fetch directives; the FIRST directive present in the policy governs
CHAINS = {
    "script": ("script-src-elem", "script-src", "default-src"),
    "style": ("style-src-elem", "style-src", "default-src"),
    "img": ("img-src", "default-src"),
    "font": ("font-src", "default-src"),
    "media": ("media-src", "default-src"),
    "frame": ("frame-src", "child-src", "default-src"),
    "worker": ("worker-src", "child-src", "script-src", "default-src"),
    "object": ("object-src", "default-src"),
    "manifest": ("manifest-src", "default-src"),
    "connect": ("connect-src", "default-src"),
    "default": ("default-src",),
    "inline-script": ("script-src-elem", "script-src", "default-src"),
    "script-attr": ("script-src-attr", "script-src", "default-src"),
    "inline-style": ("style-src-elem", "style-src", "default-src"),
    "style-attr": ("style-src-attr", "style-src", "default-src"),
}
INLINE_KINDS = frozenset(("inline-script", "script-attr", "inline-style", "style-attr"))
_PRELOAD_AS = {"script": "script", "style": "style", "font": "font", "image": "img", "fetch": "connect",
               "audio": "media", "video": "media", "track": "media", "worker": "worker", "sharedworker": "worker",
               "document": "frame", "embed": "object", "object": "object"}
_ICON_RELS = frozenset(("icon", "shortcut", "apple-touch-icon", "apple-touch-icon-precomposed", "mask-icon"))
_PREFETCH_RELS = frozenset(("prefetch", "prerender", "next"))


def _link_kind(attrs):
    rels = set(attrs.get("rel", "").lower().split())
    if "stylesheet" in rels:
        return "style"
    if rels & _ICON_RELS:
        return "img"
    if "manifest" in rels:
        return "manifest"
    if "modulepreload" in rels:
        return "script"
    if "preload" in rels:
        return _PRELOAD_AS.get(attrs.get("as", "").lower(), "default")
    if rels & _PREFETCH_RELS:
        return "connect"
    return "default"  # an unknown rel is judged by default-src alone


def _attr_kind(tag, attr, attrs, context):
    if attr in ("srcset", "imagesrcset", "poster"):
        return "img"
    if tag == "script":
        return "script"
    if tag == "link":
        return _link_kind(attrs)
    if tag in ("img", "image", "input"):
        return "img"
    if tag == "iframe":
        return "frame"
    if tag in ("embed", "object"):
        return "object"
    if tag in ("video", "audio", "track"):
        return "media"
    if tag == "source":
        return "media" if context in ("video", "audio") else "img"
    return "default"


_CSS_COMMENT = re.compile(r"/\*.*?\*/", re.DOTALL)
_CSS_STR = r"\"([^\"]*)\"|'([^']*)'"
_CSS_IMPORT = re.compile(r"@import\s*(?:url\(\s*(?:" + _CSS_STR + r"|([^)\s]*))\s*\)|" + _CSS_STR + r")", re.IGNORECASE)
_CSS_FONT_FACE = re.compile(r"@font-face\s*\{[^}]*\}", re.IGNORECASE)
_CSS_URL = re.compile(r"url\(\s*(?:" + _CSS_STR + r"|([^)\s]*))\s*\)", re.IGNORECASE)
_CSS_IMAGE_SET = re.compile(r"image-set\(([^)]*)\)", re.IGNORECASE)
_CSS_STRING = re.compile(_CSS_STR)
JS_TYPES = frozenset(("", "module", "text/javascript", "application/javascript", "application/x-javascript",
                      "text/ecmascript", "application/ecmascript", "text/jscript", "text/livescript"))
_URL_ATTRS_ANY_TAG = ("href", "src", "action", "formaction", "data")
_BACKGROUND_TAGS = frozenset(("body", "table", "thead", "tbody", "tfoot", "tr", "td", "th"))


def css_loads(css):
    """(kind, url) for every fetch a stylesheet text starts: `@import` (style), `url()` inside `@font-face` (font),
    every other `url()` and every `image-set()` string (img)."""
    css = _CSS_COMMENT.sub(" ", css)
    found = []
    for m in _CSS_IMPORT.finditer(css):
        found.append(("style", next(g for g in m.groups() if g is not None)))
    css = _CSS_IMPORT.sub(" ", css)
    for face in _CSS_FONT_FACE.finditer(css):
        found.extend(("font", next(g for g in m.groups() if g is not None)) for m in _CSS_URL.finditer(face.group(0)))
    css = _CSS_FONT_FACE.sub(" ", css)
    found.extend(("img", next(g for g in m.groups() if g is not None)) for m in _CSS_URL.finditer(css))
    for call in _CSS_IMAGE_SET.finditer(css):
        found.extend(("img", next(g for g in m.groups() if g is not None)) for m in _CSS_STRING.finditer(call.group(1)))
    return found


class _ResourceParser(HTMLParser):
    """Collect every load a page starts with a real HTML parser (tag and attribute names arrive lower-cased,
    attribute values are entity-unescaped): URL attributes of resource tags, CSS fetches (style attributes, `<style>`
    bodies, the `background` attribute), and inline script / style. Each load carries its fetch kind."""

    TAGS = frozenset(("link", "script", "img", "iframe", "source", "video", "audio", "embed", "object",
                      "track", "input", "image"))
    CONTEXTS = ("video", "audio", "picture")

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.loads = []
        self.metas = []  # the content of every <meta http-equiv="content-security-policy">
        self._open = []  # the enclosing video / audio / picture elements
        self._style = None  # (nonce, [text parts]) while inside a <style> element
        self._script = None  # (nonce, [text parts]) while inside an inline <script>

    def _add(self, kind, value, nonce=""):
        try:
            resolved = resolve_load(value)
        except UnparsedURL:
            # fail closed: never allowed by any policy, so the guard goes red
            self.loads.append(Load(kind, UNPARSED_PREFIX + value, "", nonce))
            return
        if resolved:
            self.loads.append(Load(kind, resolved[0], resolved[1], nonce))

    def _add_css(self, css, nonce=""):
        for kind, value in css_loads(css):
            self._add(kind, value, nonce)

    def handle_data(self, data):
        if self._style is not None:
            self._style[1].append(data)

    def handle_endtag(self, tag):
        if tag in self.CONTEXTS and tag in self._open:
            del self._open[len(self._open) - 1 - self._open[::-1].index(tag):]
        if tag == "style" and self._style is not None:
            nonce, parts = self._style
            self._style = None
            self._add_css("".join(parts), nonce)
        if tag == "script":
            self._script = None

    def handle_starttag(self, tag, attrs):
        context = self._open[-1] if self._open else ""
        if tag in self.CONTEXTS:
            self._open.append(tag)
        found = {}
        for k, v in attrs:
            found.setdefault(k, v or "")  # the HTML parser keeps the FIRST duplicate attribute
        attrs = found
        nonce = attrs.get("nonce", "")
        self._inline_and_css(tag, attrs, nonce)
        if tag not in self.TAGS:
            return
        rels = set(attrs.get("rel", "").lower().split())
        if tag == "link" and rels and rels <= NON_LOADING_RELS:
            return
        values = [(k, attrs[k]) for k in URL_ATTRS if k in attrs]
        for key in ("srcset", "imagesrcset"):
            if key in attrs:
                values.extend((key, c.split()[0]) for c in attrs[key].split(",") if c.split())
        for attr, value in values:
            if tag == "script" and attr != "src":
                continue
            self._add(_attr_kind(tag, attr, attrs, context), value, nonce)

    def _inline_and_css(self, tag, attrs, nonce):
        if tag == "meta" and attrs.get("http-equiv", "").strip().lower() == "content-security-policy":
            self.metas.append(attrs.get("content", ""))
        if tag == "style":
            self.loads.append(Load("inline-style", INLINE_ORIGIN, "", nonce))
            self._style = (nonce, [])
        if tag == "script" and "src" not in attrs and attrs.get("type", "").strip().lower() in JS_TYPES:
            self.loads.append(Load("inline-script", INLINE_ORIGIN, "", nonce))
        if "style" in attrs:
            self.loads.append(Load("style-attr", INLINE_ORIGIN, "", ""))
            self._add_css(attrs["style"])
        if tag in _BACKGROUND_TAGS and "background" in attrs:
            self._add("img", attrs["background"])
        for name, value in attrs.items():
            if name.startswith("on"):
                self.loads.append(Load("script-attr", INLINE_ORIGIN, "", ""))
            elif name in _URL_ATTRS_ANY_TAG and normalise_url(value).lower().startswith("javascript:"):
                self.loads.append(Load("script-attr", INLINE_ORIGIN, "", ""))


def _parse_page(html):
    parser = _ResourceParser()
    parser.feed(html)
    parser.close()
    return parser


def page_loads(html):
    """Every load of a page as Load tuples: network, page-relative (SELF_ORIGIN), data:, blob:, and the inline
    script / style behaviours. A URL that cannot be parsed has the origin `unparsed:<value>` so the guard fails
    instead of dropping it."""
    return _parse_page(html).loads


def loaded_resources(html):
    """The network (http / https, protocol-relative counts as https) loads of `page_loads`, plus unparsed ones."""
    return [ld for ld in page_loads(html) if ld.origin not in NON_NETWORK_ORIGINS]


def loaded_origins(html):
    """The distinct origins of `loaded_resources`."""
    return {load.origin for load in loaded_resources(html)}


Source = collections.namedtuple("Source", "scheme host port path")
Policy = collections.namedtuple("Policy", "directives invalid")
# CSP3 host-source: [scheme "://"] host [":" port] [path]; host-char is ALPHA / DIGIT / "-" only, so IPv6
# literals and underscores are NOT valid sources (browsers ignore them); a path has no ? # ; or ,
_CSP_HOST_SOURCE = re.compile(
    r"^(?:(?P<scheme>[a-z][a-z0-9+.\-]*)://)?(?P<host>\*|(?:\*\.)?[a-z0-9\-]+(?:\.[a-z0-9\-]+)*)"
    r"(?::(?P<port>[0-9]+|\*))?(?P<path>/[^\s;,?#]*)?$", re.IGNORECASE)
_CSP_SCHEME_SOURCE = re.compile(r"^([a-z][a-z0-9+.\-]*):$", re.IGNORECASE)
_NONCE = re.compile(r"^nonce-([A-Za-z0-9+/_\-]+=*)$")
_HASH = re.compile(r"^(?:sha256|sha384|sha512)-[A-Za-z0-9+/_\-]+=*$", re.IGNORECASE)
_KEYWORDS = frozenset(("self", "none", "unsafe-inline", "unsafe-eval", "unsafe-hashes", "strict-dynamic",
                       "report-sample", "wasm-unsafe-eval", "inline-speculation-rules", "trusted-types-eval",
                       "unsafe-allow-redirects"))
_SOURCE_LIST_DIRECTIVES = frozenset(d for chain in CHAINS.values() for d in chain) | frozenset((
    "script-src-attr", "style-src-attr", "prefetch-src", "base-uri", "form-action", "frame-ancestors", "navigate-to"))
_STRICT_DYNAMIC_DIRECTIVES = frozenset(("script-src", "script-src-elem", "default-src"))
_ASCII_SPACE = re.compile("[ \t\n\r\f]+")


def _classify(token):
    """One CSP source expression as (kind, value), or None when it is invalid (browsers ignore it)."""
    if len(token) > 1 and token.startswith("'") and token.endswith("'"):
        inner = token[1:-1]
        if inner.lower() in _KEYWORDS:
            return "keyword", inner.lower()
        nonce = _NONCE.match(inner)
        if nonce:
            return "nonce", nonce.group(1)
        if _HASH.match(inner):
            return "hash", inner
        return None
    scheme_only = _CSP_SCHEME_SOURCE.match(token)
    if scheme_only:
        return "scheme", Source(scheme_only.group(1).lower(), "", "", "")
    m = _CSP_HOST_SOURCE.match(token)
    if not m:
        return None
    scheme = (m.group("scheme") or PAGE_SCHEME).lower()
    port = m.group("port") or ""
    if port != "*" and port:
        if int(port) > MAX_PORT:
            return None
        port = str(int(port))
        port = "" if port == DEFAULT_PORTS.get(scheme) else port
    return "host", Source(scheme, m.group("host").lower(), port, m.group("path") or "")


def parse_policy(csp):
    """Policy(directives, invalid): directive name (lower-case; the FIRST occurrence of a duplicate wins) mapped
    to its classified source expressions, and the (directive, token) pairs that are invalid and so match
    nothing. Directives that are not source lists (sandbox, report-uri, ...) are kept as raw tokens."""
    directives, invalid = {}, []
    for part in csp.split(";"):
        tokens = [t for t in _ASCII_SPACE.split(part) if t]
        if not tokens:
            continue
        name = tokens[0].lower()
        if not re.fullmatch(r"[a-z0-9\-]+", name) or name in directives:
            continue
        entries = []
        for token in tokens[1:]:
            if name not in _SOURCE_LIST_DIRECTIVES:
                entries.append(("raw", token))
                continue
            entry = _classify(token)
            if entry is None:
                invalid.append((name, token))
            else:
                entries.append(entry)
        directives[name] = entries
    return Policy(directives, invalid)


def csp_sources(csp):
    """Flat view of a CSP value: every valid scheme / host source of every directive as Source(scheme, host, port,
    path); scheme-only sources have host ''. Scheme and host are case-insensitive, `:*` is the explicit wildcard
    port, the default port is dropped. Invalid expressions are left out (they match nothing). Where
    'strict-dynamic' is present in a script directive (or default-src) its host and scheme sources are ignored by
    browsers and are left out too. The guard itself uses `load_allowed`, which does not flatten."""
    policy = parse_policy(csp)
    sources = []
    for name, entries in policy.directives.items():
        strict = name in _STRICT_DYNAMIC_DIRECTIVES and ("keyword", "strict-dynamic") in entries
        for kind, value in entries:
            if kind in ("scheme", "host") and not strict:
                sources.append(value)
    return sources


def _split_origin(origin):
    scheme, _, rest = origin.partition("://")
    if rest.startswith("["):
        host, _, tail = rest.partition("]")
        return scheme, host + "]", tail[1:]
    host, _, port = rest.partition(":")
    return scheme, host, port


def _path_matches(source_path, path):
    """CSP3 path-part matching: exact, or a prefix when the source path ends in a slash; both percent-decoded."""
    want = urllib.parse.unquote_to_bytes(source_path)
    got = urllib.parse.unquote_to_bytes(path)
    return got.startswith(want) if want.endswith(b"/") else got == want


def source_allows(source, origin, path=None):
    """True when the CSP scheme / host source admits the loaded origin string (`scheme://host[:port]`) and URL
    path. A source with a path part cannot admit a check that supplies no path (`path=None`): fail closed."""
    if origin in NON_NETWORK_ORIGINS:
        # only a scheme source can match these: `data:` / `blob:` themselves, http: / https: for a page-relative URL
        # (the page is served over https); host sources and the wildcard never admit data: or blob:
        if source.host:
            return False
        if origin == SELF_ORIGIN:
            return source.scheme in ("http", "https")
        return source.scheme + ":" == origin
    scheme, host, port = _split_origin(origin)
    if source.scheme != scheme and not (source.scheme == "http" and scheme == "https"):
        return False  # a scheme-part matches the same scheme, and http: also matches https:
    if not source.host:
        return True  # a scheme source
    if source.host == "*":
        host_ok = True
    elif source.host.startswith("*."):
        host_ok = host.endswith(source.host[1:]) and len(host) > len(source.host) - 1
    else:
        host_ok = host == source.host
    if not host_ok or not (source.port == "*" or source.port == port):
        return False
    if source.path:
        return path is not None and _path_matches(source.path, path)
    return True


def effective_directive(policy, kind):
    """The directive that governs a resource kind (CSP3 fallback chain), or None when none is present, which
    leaves the load unrestricted."""
    for name in CHAINS.get(kind, CHAINS["default"]):
        if name in policy.directives:
            return name
    return None


def load_allowed(policy, load):
    """True when the load passes the source list of ITS governing directive; source lists are never merged."""
    if load.origin.startswith(UNPARSED_PREFIX):
        return False
    name = effective_directive(policy, load.kind)
    if name is None:
        return True
    entries = policy.directives[name]
    if load.origin == INLINE_ORIGIN:
        # nonce and hash sources make browsers ignore 'unsafe-inline' for elements (not for attributes);
        # hash sources are not computed here, so they admit nothing (fail closed)
        guarded = any(kind in ("nonce", "hash") for kind, _ in entries) and load.kind in ("inline-script", "inline-style")
        if load.nonce and ("nonce", load.nonce) in entries:
            return True
        return ("keyword", "unsafe-inline") in entries and not guarded
    if load.kind in ("script", "style") and load.nonce and ("nonce", load.nonce) in entries:
        return True
    if load.kind == "script" and ("keyword", "strict-dynamic") in entries:
        return False  # 'strict-dynamic' makes browsers ignore host and scheme sources for scripts
    if load.origin == SELF_ORIGIN and ("keyword", "self") in entries:
        return True
    return any(kind in ("scheme", "host") and source_allows(value, load.origin, load.path) for kind, value in entries)


def _policy_lines(values):
    """Each CSP value split into its policies (a header value joins several with commas)."""
    return [p.strip() for v in values for p in v.split(",") if p.strip()]


def policies_of(html, header_values):
    """Every policy a page gets: each header line / comma-separated policy, then each `<meta http-equiv>` policy."""
    return [parse_policy(p) for p in _policy_lines(list(header_values) + _parse_page(html).metas)]


def blocked_loads(html, header_values):
    """The loads of a page that at least one of its policies blocks; policies are enforced independently, so a load
    must pass ALL of them (#7591)."""
    policies = policies_of(html, header_values)
    return [ld for ld in page_loads(html) if not all(load_allowed(p, ld) for p in policies)]


def _pattern_regex(pattern):
    """A Cloudflare `_headers` URL pattern: `*` is a splat, `:name` a placeholder for one path segment."""
    out = []
    for part in re.split(r"(\*|:[A-Za-z][A-Za-z0-9_]*)", pattern):
        out.append(".*" if part == "*" else "[^/]+" if part.startswith(":") and len(part) > 1 else re.escape(part))
    return re.compile("^" + "".join(out) + "$")


def header_policies(headers_text, path):
    """The Content-Security-Policy values (one per comma-separated policy) of every `_headers` rule whose pattern
    matches the served path, in file order (Cloudflare adds the headers of all matching rules)."""
    values, current = [], None
    for line in headers_text.splitlines():
        if not line.strip():
            continue
        if line[0] not in " \t":
            current = _pattern_regex(line.strip()).match(path) is not None
        elif current:
            name, _, value = line.strip().partition(":")
            if name.strip().lower() == "content-security-policy":
                values.append(value.strip())
    return _policy_lines(values)


GOOGLE_FONTS_CSS_ORIGIN = "https://fonts.googleapis.com"
GOOGLE_FONTS_FILE_LOAD = Load("font", "https://fonts.gstatic.com", "/s/font.woff2", "")


def derived_loads(loads):
    """Loads a fetched stylesheet starts that no page tag shows: the Google Fonts stylesheet names its font files on
    fonts.gstatic.com, so any stylesheet load from the Fonts API origin implies that font load (derived, not
    hand-listed per page)."""
    if any(ld.kind == "style" and ld.origin == GOOGLE_FONTS_CSS_ORIGIN for ld in loads):
        return [GOOGLE_FONTS_FILE_LOAD]
    return []


def served_paths(page_name):
    """The URL paths a page is served at: its file, its extension-less pretty URL, and `/` for the index."""
    stem = page_name[:-len(".html")] if page_name.endswith(".html") else page_name
    return ["/" + page_name, "/" + stem] + (["/"] if stem == "index" else [])
