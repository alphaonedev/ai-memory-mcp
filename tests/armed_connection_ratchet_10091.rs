//! #10091 — whole-tree allowlist ratchet: every raw `rusqlite` connection
//! opener in the source tree is a pinned, reasoned site.
//!
//! A writable `rusqlite::Connection` that does not come from
//! `storage::open` / `storage::open_armed` carries no row-attestation
//! funnel, so a write it makes to an attested table is unattested and the
//! store fails verification for good. `storage::open_armed` is the one
//! constructor that hands out a writable handle off the migrating `open`;
//! `storage::open_unmigrated` refuses attested writes outright. This test
//! makes every other opener an explicit, reasoned exception.
//!
//! What it counts, per `.rs` file, after stripping comments (nested block
//! comments included), string, byte, C and raw string literals and char
//! literals (lifetimes are kept):
//!
//! - an opener (`open`, `open_with_flags`, `open_with_flags_and_vfs`,
//!   `open_in_memory`, `open_in_memory_with_flags`) after `::` whose
//!   qualifier is `Connection` or ANY alias of it declared anywhere in the
//!   tree (`Connection as X`, `type X = ...Connection;`), including the
//!   `<Connection>::open` form, a call, a fn pointer, a const or static
//!   table entry, a match arm: every form spells `Q::opener`;
//! - any identifier starting `sqlite3_open` (the raw FFI openers).
//!
//! Scope: every `.rs` file under the crate root, whatever the directory
//! (src, tests, benches, examples, build.rs, vendored crates). The left-out
//! directories are listed in [`SKIPPED`] with their reasons. The pinned
//! table is exact in both directions: a new site, a removed site, a moved
//! site and a new file all fail.
//!
//! The table was generated by an independent scanner (a Python regex
//! pass over the same tree), not by this test.

