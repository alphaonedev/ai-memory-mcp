/// The counter itself: every spelling of an opener counts once, and the
/// same text inside a comment or literal counts zero.
#[test]
fn the_counter_sees_every_form_and_no_literal_10091() {
    let quals: BTreeSet<String> = ["Connection", "C", "Db"]
        .into_iter()
        .map(String::from)
        .collect();
    let cases: &[(&str, usize)] = &[
        ("let c = Connection::open(p);", 1),
        ("let c = rusqlite::Connection::open_in_memory();", 1),
        ("const F: fn(&Path) -> R = Connection::open;", 1),
        (
            "static T: [fn(&Path) -> R; 2] = [Connection::open, C::open_with_flags];",
            2,
        ),
        (
            "match k { 0 => Db::open(p), _ => <Connection>::open_with_flags_and_vfs(p, f, v) }",
            2,
        ),
        ("Connection :: open_in_memory_with_flags(f)", 1),
        ("unsafe { ffi::sqlite3_open_v2(a, b, c, d) }", 1),
        ("// Connection::open(p)", 0),
        ("/* outer /* Connection::open(p) */ still */ x", 0),
        ("let s = \"Connection::open(p)\";", 0),
        ("let s = r#\"Connection::open(\"p\")\"#;", 0),
        ("let c = '\"'; Connection::open(p);", 1),
        ("fn f<'a>(x: &'a str) { Connection::open(x); }", 1),
        ("File::open(p); Other::open(p);", 0),
    ];
    for (src, want) in cases {
        assert_eq!(count(&strip(src), &quals), *want, "{src}");
    }
    assert_eq!(
        aliases(&strip(
            "use rusqlite::Connection as Db; type C = rusqlite::Connection; type N = Other;"
        )),
        vec!["Db".to_string(), "C".to_string()]
    );
}
