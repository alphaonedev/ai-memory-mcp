//! #10176 — whole-tree allowlist ratchet: the only way a lib test re-runs the
//! test binary is the shared builder in `src/test_support.rs`
//! (`SandboxedTestChild`), which hands the child an isolated `HOME`,
//! `XDG_CONFIG_HOME` and `AI_MEMORY_WITNESS_KEY_DIR`.
//!
//! A child that re-runs the test executable with the parent's environment (or
//! with `env_clear()`, which leaves `HOME` unset so the child resolves the
//! passwd home) can open the real user's key and witness custody directories.
//! Fourteen lib-test spawners did exactly that before #10176. This test makes
//! the class impossible to reintroduce by accident: every mention of the
//! executable-path call (`current_exe`, the `/proc/self/exe` spelling) in a
//! tracked Rust file is a pinned, reasoned site, and the builder module is the
//! one file that may hold any number of them.
//!
//! What it counts, per `.rs` file, after blanking comments (nested block
//! comments included) and string, raw string and char literals:
//!
//! - every whole-identifier `current_exe`, whatever spells it: a path call, a
//!   `use ... as alias` import, a bare imported call, a `let` binding, a
//!   `macro_rules!` body, a fn-pointer or a closure;
//! - every `/proc/self/exe` literal (counted on the raw text, since it sits in
//!   a string).
//!
//! Scope: every `.rs` file under the crate root, whatever the directory (src,
//! tests, benches, examples, build.rs). The left-out directories are listed in
//! [`SKIPPED`] with their reasons. The table is exact in both directions: a new
//! site, a removed site, a moved site and a new file all fail.
//!
//! The table was generated by an independent scanner (a Python pass over the
//! same tree), not by this test.

