fn crate_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

fn walk(dir: &Path, root: &Path, out: &mut Vec<PathBuf>) {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return;
    };
    let mut entries: Vec<_> = entries.flatten().collect();
    entries.sort_by_key(std::fs::DirEntry::file_name);
    for entry in entries {
        let path = entry.path();
        let Ok(kind) = entry.file_type() else {
            continue;
        };
        if kind.is_symlink() {
            continue;
        }
        if kind.is_dir() {
            let rel = path.strip_prefix(root).unwrap_or(&path);
            if SKIPPED.iter().any(|(name, _)| rel == Path::new(name)) {
                continue;
            }
            walk(&path, root, out);
        } else if path.extension().is_some_and(|ext| ext == "rs") {
            out.push(path);
        }
    }
}

/// The number of executable-path sites in one source text.
fn count_sites(src: &str) -> usize {
    ident_offsets(&mask(src), EXE_IDENT).len() + src.matches(PROC_SELF_EXE).count()
}

/// Sites per tracked `.rs` file (relative, `/`-separated), zero rows dropped.
fn scan(root: &Path) -> BTreeMap<String, usize> {
    let mut files = Vec::new();
    walk(root, root, &mut files);
    let mut sites = BTreeMap::new();
    for file in files {
        let rel = file
            .strip_prefix(root)
            .expect("walked path is under the root")
            .to_string_lossy()
            .replace('\\', "/");
        let text = std::fs::read_to_string(&file)
            .unwrap_or_else(|e| panic!("#10176: read {rel}: {e}; an unreadable file is not clean"));
        let n = count_sites(&text);
        if n > 0 {
            sites.insert(rel, n);
        }
    }
    sites
}

fn pinned() -> BTreeMap<String, usize> {
    ALLOWLIST
        .iter()
        .map(|(path, n, _)| ((*path).to_string(), *n))
        .collect()
}

#[test]
fn only_the_builder_spawns_the_test_executable_10176() {
    let mut observed = scan(&crate_root());
    observed.remove(CHOKEPOINT);
    observed.remove(SELF_FILE);
    let pinned = pinned();
    let mut problems = Vec::new();
    for (path, n) in &observed {
        match pinned.get(path) {
            None => problems.push(format!(
                "{path}: {n} executable-path site(s) outside the builder; a lib-test child \
                 must come from `crate::test_support::SandboxedTestChild` so it gets an \
                 isolated HOME, XDG_CONFIG_HOME and AI_MEMORY_WITNESS_KEY_DIR (#10176)"
            )),
            Some(want) if want != n => problems.push(format!(
                "{path}: pinned {want} site(s), found {n}; re-justify the row (#10176)"
            )),
            Some(_) => {}
        }
    }
    for path in pinned.keys() {
        if !observed.contains_key(path) {
            problems.push(format!(
                "{path}: pinned but no site found; remove the stale row (#10176)"
            ));
        }
    }
    assert!(problems.is_empty(), "#10176:\n{}", problems.join("\n"));
}

