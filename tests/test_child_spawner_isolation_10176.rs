fn crate_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

fn walk(dir: &Path, root: &Path, out: &mut Vec<PathBuf>) {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return;
    };
    let mut entries: Vec<_> = entries.flatten().collect();
    entries.sort_by_key(std::fs::DirEntry::file_name);
    for entry in entries {
        let path = entry.path();
        let Ok(kind) = entry.file_type() else {
            continue;
        };
        if kind.is_symlink() {
            continue;
        }
        if kind.is_dir() {
            let rel = path.strip_prefix(root).unwrap_or(&path);
            if SKIPPED.iter().any(|(name, _)| rel == Path::new(name)) {
                continue;
            }
            walk(&path, root, out);
        } else if path.extension().is_some_and(|ext| ext == "rs") {
            out.push(path);
        }
    }
}

/// The number of executable-path sites in one source text.
fn count_sites(src: &str) -> usize {
    ident_offsets(&mask(src), EXE_IDENT).len() + src.matches(PROC_SELF_EXE).count()
}

/// Sites per tracked `.rs` file (relative, `/`-separated), zero rows dropped.
fn scan(root: &Path) -> BTreeMap<String, usize> {
    let mut files = Vec::new();
    walk(root, root, &mut files);
    let mut sites = BTreeMap::new();
    for file in files {
        let rel = file
            .strip_prefix(root)
            .expect("walked path is under the root")
            .to_string_lossy()
            .replace('\\', "/");
        let text = std::fs::read_to_string(&file)
            .unwrap_or_else(|e| panic!("#10176: read {rel}: {e}; an unreadable file is not clean"));
        let n = count_sites(&text);
        if n > 0 {
            sites.insert(rel, n);
        }
    }
    sites
}

fn pinned() -> BTreeMap<String, usize> {
    ALLOWLIST
        .iter()
        .map(|(path, n, _)| ((*path).to_string(), *n))
        .collect()
}

#[test]
fn only_the_builder_spawns_the_test_executable_10176() {
    let mut observed = scan(&crate_root());
    observed.remove(CHOKEPOINT);
    observed.remove(SELF_FILE);
    let pinned = pinned();
    let mut problems = Vec::new();
    for (path, n) in &observed {
        match pinned.get(path) {
            None => problems.push(format!(
                "{path}: {n} executable-path site(s) outside the builder; a lib-test child \
                 must come from `crate::test_support::SandboxedTestChild` so it gets an \
                 isolated HOME, XDG_CONFIG_HOME and AI_MEMORY_WITNESS_KEY_DIR (#10176)"
            )),
            Some(want) if want != n => problems.push(format!(
                "{path}: pinned {want} site(s), found {n}; re-justify the row (#10176)"
            )),
            Some(_) => {}
        }
    }
    for path in pinned.keys() {
        if !observed.contains_key(path) {
            problems.push(format!(
                "{path}: pinned but no site found; remove the stale row (#10176)"
            ));
        }
    }
    assert!(problems.is_empty(), "#10176:\n{}", problems.join("\n"));
}

#[test]
fn no_lib_source_file_outside_the_builder_spawns_the_test_executable_10176() {
    // The invariant of the issue in its own words: under src/, only the builder
    // module and the one product path lookup may name the executable path.
    let src_rows: Vec<&str> = ALLOWLIST
        .iter()
        .map(|(path, _, _)| *path)
        .filter(|path| path.starts_with("src/"))
        .collect();
    assert_eq!(
        src_rows,
        vec!["src/cli/install.rs"],
        "#10176: a src/ file other than {CHOKEPOINT} may not spawn the test executable; \
         the only src/ row is the product path lookup"
    );
}

#[test]
fn every_pinned_row_and_skip_has_a_reason_10176() {
    for (path, n, why) in ALLOWLIST {
        assert!(*n > 0, "#10176: row {path} pins zero sites");
        assert!(
            why.trim().len() >= 20,
            "#10176: row {path} needs a real reason, got {why:?}"
        );
        assert!(
            crate_root().join(path).is_file(),
            "#10176: row {path} names a file that does not exist"
        );
    }
    for (dir, why) in SKIPPED {
        assert!(
            why.trim().len() >= 10,
            "#10176: skipped dir {dir} needs a reason"
        );
    }
    let unique: std::collections::BTreeSet<_> = ALLOWLIST.iter().map(|(p, _, _)| *p).collect();
    assert_eq!(unique.len(), ALLOWLIST.len(), "#10176: duplicate rows");
}

#[test]
fn the_counter_sees_every_form_and_no_literal_10176() {
    // (source, expected sites). Every spelling of the construct a spawner can use.
    let cases: &[(&str, usize)] = &[
        // literal call, fully qualified
        ("let p = std::env::current_exe().unwrap();", 1),
        // short path
        ("let p = env::current_exe()?;", 1),
        // alias import: the import line itself is a site
        (
            "use std::env::current_exe as exe_path;\nlet p = exe_path();",
            1,
        ),
        // plain import plus a bare call: two sites
        ("use std::env::current_exe;\nlet p = current_exe();", 2),
        // let binding of a fn pointer
        ("let f = std::env::current_exe;\nlet p = f();", 1),
        // constructor argument on a continuation line
        (
            "Command::new(\n    std::env::current_exe().expect(\"x\"),\n)",
            1,
        ),
        // inside a macro body
        ("macro_rules! m { () => { std::env::current_exe() }; }", 1),
        // the Linux spelling, in a string
        ("let p = \"/proc/self/exe\";", 1),
        // a raw string with the Linux spelling
        ("let p = r#\"/proc/self/exe\"#;", 1),
        // never counted: comments, doc comments, string and char literals,
        // longer identifiers
        ("// std::env::current_exe()", 0),
        ("/// `current_exe()` in docs", 0),
        ("/* current_exe() /* nested */ current_exe() */", 0),
        ("let s = \"current_exe\";", 0),
        ("let s = r#\"current_exe\"#;", 0),
        ("let my_current_exe_path = 1; let current_exe_2 = 2;", 0),
        ("let c = '\"'; let d = 1;", 0),
    ];
    for (src, want) in cases {
        assert_eq!(
            count_sites(src),
            *want,
            "#10176: counter disagrees on source {src:?}"
        );
    }
}

#[test]
fn a_new_file_outside_src_is_a_site_10176() {
    let base = scratch_dir(&crate_root().join(".local-runs"));
    let nested = base.join("nested");
    std::fs::create_dir_all(&nested).expect("create scan fixture dir");
    std::fs::write(
        nested.join("spawner.rs"),
        "fn f() { let _ = std::env::current_exe(); }\n",
    )
    .expect("write fixture");
    std::fs::write(nested.join("clean.rs"), "fn g() {}\n").expect("write fixture");
    let sites = scan(&base);
    std::fs::remove_dir_all(&base).expect("remove scan fixture");
    assert_eq!(
        sites.into_iter().collect::<Vec<_>>(),
        vec![("nested/spawner.rs".to_string(), 1)],
        "#10176: a spawner in any directory is found, a clean file is not"
    );
}

/// A fresh scratch directory under `parent` (the gitignored `.local-runs`, never
/// a tmp path), named from the pid and a counter.
fn scratch_dir(parent: &Path) -> PathBuf {
    static NEXT: std::sync::atomic::AtomicUsize = std::sync::atomic::AtomicUsize::new(0);
    let n = NEXT.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
    let dir = parent.join(format!("ai-memory-10176-scan-{}-{n}", std::process::id()));
    std::fs::create_dir_all(&dir).expect("create scratch dir");
    dir
}
